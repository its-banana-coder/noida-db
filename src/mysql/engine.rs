/// Applies a `SHOW ... LIKE 'pattern'` filter to a two-column name/value
/// table (MySQL's `LIKE` here matches the first column, case-insensitively).
/// A `WHERE` filter isn't evaluated -- every row is returned, which only
/// ever over-reports to clients that look values up by name (JDBC's old
/// `SHOW VARIABLES WHERE Variable_name = ...` probe), never drops one.
fn show_filtered(table: &[(&str, &str)], filter: Option<&ShowStatementFilter>) -> Vec<Vec<Value>> {
    let pattern = match filter {
        Some(ShowStatementFilter::Like(p)) | Some(ShowStatementFilter::NoKeyword(p)) => {
            Some(p.as_str())
        }
        _ => None,
    };
    table
        .iter()
        .filter(|(name, _)| {
            pattern.is_none_or(|p| crate::mysql::exec::mysql_like(name, p, Some('\\')))
        })
        .map(|(n, v)| vec![Value::Text((*n).into()), Value::Text((*v).into())])
        .collect()
}

/// `Some(mode)` if `set` assigns `sql_mode` (`SET sql_mode = '...'`,
/// `SET SESSION sql_mode = ...`, `SET @@sql_mode = DEFAULT`, ...).
fn sql_mode_assignment(set: &sqlparser::ast::Set) -> Option<crate::mysql::sqlmode::SqlMode> {
    use crate::mysql::sqlmode::SqlMode;
    use sqlparser::ast::{Expr as E, Set, Value as V};
    let pairs: Vec<(String, &E)> = match set {
        Set::SingleAssignment { variable, values, .. } => {
            values.first().map(|v| vec![(variable.to_string(), v)]).unwrap_or_default()
        }
        Set::MultipleAssignments { assignments } => {
            assignments.iter().map(|a| (a.name.to_string(), &a.value)).collect()
        }
        _ => vec![],
    };
    let mut out = None;
    for (name, value) in pairs {
        let name = name.trim_start_matches('@').to_ascii_lowercase();
        if name.rsplit('.').next() != Some("sql_mode") {
            continue;
        }
        out = match value {
            E::Value(v) => match &v.value {
                V::SingleQuotedString(s) | V::DoubleQuotedString(s) => Some(SqlMode::parse(s)),
                _ => None,
            },
            E::Identifier(i) if i.value.eq_ignore_ascii_case("default") => Some(SqlMode::default()),
            E::Identifier(i) => Some(SqlMode::parse(&i.value)),
            _ => None,
        }
        .or(out);
    }
    out
}

/// `SELECT ... FROM ... INTO @a, @b` (MySQL also takes INTO last): moved
/// before the top-level FROM, where the SQL parser expects it.
pub fn rewrite_trailing_into(sql: &str) -> Option<String> {
    let re = regex_lite::Regex::new(
        r"(?is)\s+into\s+(@[A-Za-z0-9_$.`@]+(?:\s*,\s*@[A-Za-z0-9_$.`@]+)*)\s*;?\s*$",
    )
    .expect("regex");
    let trimmed = sql.trim_start();
    if trimmed.len() < 6 || !trimmed[..6].eq_ignore_ascii_case("SELECT") {
        return None;
    }
    let m = re.captures(sql)?;
    let head = &sql[..m.get(0)?.start()];
    // The top-level FROM: outside parentheses and quotes.
    let bytes = head.as_bytes();
    let (mut depth, mut quote) = (0i32, None::<u8>);
    let mut from = None;
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        match quote {
            Some(q) => {
                if c == b'\\' {
                    i += 1;
                } else if c == q {
                    quote = None;
                }
            }
            None => match c {
                b'\'' | b'"' | b'`' => quote = Some(c),
                b'(' => depth += 1,
                b')' => depth -= 1,
                _ if depth == 0
                    && head[i..].len() >= 4
                    && head[i..i + 4].eq_ignore_ascii_case("FROM")
                    && (i == 0 || bytes[i - 1].is_ascii_whitespace() || bytes[i - 1] == b')')
                    && head
                        .as_bytes()
                        .get(i + 4)
                        .is_none_or(|b| b.is_ascii_whitespace() || *b == b'(') =>
                {
                    from = Some(i);
                    break;
                }
                _ => {}
            },
        }
        i += 1;
    }
    let from = from?;
    Some(format!("{}INTO {} {}", &head[..from], &m[1], &head[from..]))
}

/// `ALTER TABLE t ... RENAME {INDEX|KEY} a TO b ...`, which the SQL parser
/// doesn't know, as a column rename of a marked name that the binder turns
/// back into an index rename.
/// `EXTRACT(DAY_SECOND FROM x)` and the other compound units, which
/// sqlparser doesn't parse: an internal `NOIDA_EXTRACT('DAY_SECOND', x)`.
pub fn rewrite_extract_units(sql: &str) -> Option<String> {
    let re = regex_lite::Regex::new(
        r"(?i)\bextract\s*\(\s*(year_month|day_hour|day_minute|day_second|day_microsecond|hour_minute|hour_second|hour_microsecond|minute_second|minute_microsecond|second_microsecond)\s+from\s+",
    )
    .expect("regex");
    re.is_match(sql).then(|| {
        re.replace_all(sql, |c: &regex_lite::Captures| {
            format!("NOIDA_EXTRACT('{}', ", c[1].to_ascii_uppercase())
        })
        .into_owned()
    })
}

/// `EXPLAIN [ANALYZE] FORMAT=TRADITIONAL stmt`, which sqlparser doesn't
/// take: TRADITIONAL is the default, so the clause is dropped.
pub fn rewrite_explain_format(sql: &str) -> Option<String> {
    let re = regex_lite::Regex::new(
        r"(?is)^(\s*(?:explain|describe|desc)(?:\s+analyze)?)\s+format\s*=\s*traditional\b",
    )
    .expect("regex");
    re.is_match(sql).then(|| re.replace(sql, "$1").into_owned())
}

pub fn rewrite_rename_key(sql: &str) -> Option<String> {
    let trimmed = sql.trim_start();
    if trimmed.len() < 11 || !trimmed[..11].eq_ignore_ascii_case("ALTER TABLE") {
        return None;
    }
    let re = regex_lite::Regex::new(
        r"(?i)\brename\s+(?:index|key)\s+(`(?:[^`]|``)+`|[A-Za-z0-9_$]+)\s+to\b",
    )
    .expect("regex");
    if !re.is_match(sql) {
        return None;
    }
    let out = re.replace_all(sql, |c: &regex_lite::Captures| {
        let name = c[1].trim_matches('`').replace("``", "`");
        format!(
            "RENAME COLUMN `{}{}` TO",
            crate::mysql::binder::RENAME_KEY_MARKER,
            name.replace('`', "``")
        )
    });
    Some(out.into_owned())
}

/// `Some(on)` if `set` assigns `autocommit` (`SET autocommit = 0`,
/// `SET @@autocommit = 1`, `SET SESSION autocommit = OFF`, ...).
/// `UPDATE a, b SET ...` (MySQL's comma join in a multi-table UPDATE)
/// as `UPDATE a CROSS JOIN b SET ...`, which the SQL parser accepts and
/// means the same. None when there's nothing to rewrite.
pub fn rewrite_comma_update(sql: &str) -> Option<String> {
    let trimmed = sql.trim_start();
    if trimmed.len() < 7 || !trimmed[..7].eq_ignore_ascii_case("UPDATE ") {
        return None;
    }
    let start = sql.len() - trimmed.len() + 7;
    let bytes = sql.as_bytes();
    let (mut depth, mut quote) = (0i32, None::<u8>);
    let mut commas = Vec::new();
    let mut i = start;
    while i < bytes.len() {
        let c = bytes[i];
        match quote {
            Some(q) => {
                if c == b'\\' {
                    i += 1;
                } else if c == q {
                    quote = None;
                }
            }
            None => match c {
                b'\'' | b'"' | b'`' => quote = Some(c),
                b'(' => depth += 1,
                b')' => depth -= 1,
                b',' if depth == 0 => commas.push(i),
                _ if depth == 0
                    && (c == b'S' || c == b's')
                    && sql[i..].len() > 3
                    && sql[i..i + 3].eq_ignore_ascii_case("SET")
                    && bytes[i - 1].is_ascii_whitespace()
                    && bytes.get(i + 3).is_some_and(|b| b.is_ascii_whitespace()) =>
                {
                    break;
                }
                _ => {}
            },
        }
        i += 1;
    }
    if commas.is_empty() || i >= bytes.len() {
        return None;
    }
    let mut out = sql.to_string();
    for &c in commas.iter().rev() {
        out.replace_range(c..c + 1, " CROSS JOIN ");
    }
    Some(out)
}

/// `Some(n)` if `set` assigns the integer variable `var`.
fn int_assignment(set: &sqlparser::ast::Set, var: &str) -> Option<i64> {
    use sqlparser::ast::{Expr as E, Set, Value as V};
    let pairs: Vec<(String, &E)> = match set {
        Set::SingleAssignment { variable, values, .. } => {
            values.first().map(|v| vec![(variable.to_string(), v)]).unwrap_or_default()
        }
        Set::MultipleAssignments { assignments } => {
            assignments.iter().map(|a| (a.name.to_string(), &a.value)).collect()
        }
        _ => vec![],
    };
    pairs.into_iter().rev().find_map(|(name, value)| {
        let name = name.trim_start_matches('@').to_ascii_lowercase();
        if name.rsplit('.').next() != Some(var) {
            return None;
        }
        match value {
            E::Value(v) => match &v.value {
                V::Number(n, _) => n.parse().ok(),
                _ => None,
            },
            _ => None,
        }
    })
}

fn bool_assignment(set: &sqlparser::ast::Set, var: &str) -> Option<bool> {
    use sqlparser::ast::{Expr as E, Set, Value as V};
    let pairs: Vec<(String, &E)> = match set {
        Set::SingleAssignment { variable, values, .. } => {
            values.first().map(|v| vec![(variable.to_string(), v)]).unwrap_or_default()
        }
        Set::MultipleAssignments { assignments } => {
            assignments.iter().map(|a| (a.name.to_string(), &a.value)).collect()
        }
        _ => vec![],
    };
    let mut out = None;
    for (name, value) in pairs {
        let name = name.trim_start_matches('@').to_ascii_lowercase();
        if name.rsplit('.').next() != Some(var) {
            continue;
        }
        out = match value {
            E::Value(v) => match &v.value {
                V::Number(n, _) => Some(n != "0"),
                V::Boolean(b) => Some(*b),
                V::SingleQuotedString(s) => Some(!s.eq_ignore_ascii_case("off") && s != "0"),
                _ => None,
            },
            E::Identifier(i) => {
                Some(i.value.eq_ignore_ascii_case("on") || i.value.eq_ignore_ascii_case("true"))
            }
            _ => None,
        }
        .or(out);
    }
    out
}

/// `ALTER TABLE t COMMENT [=] '...'`, which the SQL parser doesn't know, as
/// a SET DEFAULT on a marked column name that the binder turns back into a
/// table-comment change.
pub fn rewrite_table_comment(sql: &str) -> Option<String> {
    let re = regex_lite::Regex::new(
        r#"(?is)^\s*alter\s+table\s+((?:`(?:[^`]|``)+`|[A-Za-z0-9_$]+)(?:\s*\.\s*(?:`(?:[^`]|``)+`|[A-Za-z0-9_$]+))?)\s+comment\s*=?\s*('(?:[^'\\]|\\.|'')*'|"(?:[^"\\]|\\.|"")*")\s*;?\s*$"#,
    )
    .expect("regex");
    let c = re.captures(sql)?;
    Some(format!(
        "ALTER TABLE {} ALTER COLUMN `{}` SET DEFAULT {}",
        &c[1],
        crate::mysql::binder::TABLE_COMMENT_MARKER,
        &c[2]
    ))
}

