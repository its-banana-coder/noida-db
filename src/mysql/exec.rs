use crate::mysql::catalog::{Column, ColumnType, DbState, Table, UniqueKey};
use crate::mysql::error::MySqlError;
use crate::mysql::plan::{
    AggFunc, ArithOp, CmpOp, Expr, InsertMode, JoinOp, Plan, SetOpKind, SortKey,
};
use crate::mysql::types::Value;
use crate::sql::numeric::Numeric;
use std::cmp::Ordering;
use std::sync::{Arc, Mutex};

pub struct Executor {
    pub db: Arc<Mutex<DbState>>,
    pub current_db: Option<String>,
    /// Values bound to `Expr::Param(i)` placeholders for this execution
    /// (from `COM_STMT_EXECUTE`'s parameter section), indexed the same way
    /// `Binder::param_counter` assigned them. Empty for a plain `COM_QUERY`
    /// or a parameterless prepared statement.
    pub params: Vec<Value>,
    /// Rows actually affected by the last `INSERT`/`UPDATE`/`DELETE` this
    /// executor ran, so the caller can report a real count in the OK
    /// packet instead of always claiming 0.
    pub last_affected_rows: u64,
    /// The AUTO_INCREMENT value generated by the last `INSERT`, if any --
    /// real MySQL's `LAST_INSERT_ID()` (and the OK packet's own field)
    /// report the *first* generated id of a multi-row INSERT, not the
    /// last, so that's what this tracks. 0 if the last statement wasn't an
    /// INSERT that generated one.
    pub last_insert_id: u64,
    /// The row count `SQL_CALC_FOUND_ROWS` computed (before `LIMIT`
    /// truncation) for the most recent query that used it, for a later
    /// `FOUND_ROWS()` call to read. Unlike `last_insert_id`/
    /// `last_affected_rows`, callers seed this from the connection's
    /// previous value before executing a statement (see `Engine::execute`
    /// and the `COM_STMT_EXECUTE` handler), since -- matching real
    /// MySQL -- it persists across intervening statements rather than
    /// resetting to 0 each time.
    pub last_found_rows: u64,
    /// The row an `INSERT ... ON DUPLICATE KEY UPDATE` would have inserted,
    /// while its assignments run, for `VALUES(col)` to read.
    insert_row: Option<Vec<Value>>,
    /// What `LAST_INSERT_ID()` returns: the connection's most recent
    /// generated id, which -- unlike `last_insert_id` (this statement's
    /// own) -- persists across later statements. Seeded by the caller.
    pub session_insert_id: u64,
    /// The session's `sql_mode` (how strictly writes are checked).
    pub sql_mode: crate::mysql::sqlmode::SqlMode,
    /// The session's `autocommit`, for `@@autocommit`.
    pub autocommit: bool,
    /// Set while evaluating the values an INSERT/UPDATE writes, where
    /// division by zero is an error in strict mode (not just NULL).
    writing: std::cell::Cell<bool>,
    /// The enclosing queries' rows while a subquery runs, innermost last
    /// (column names only, no rows), so a correlated reference to an outer
    /// column resolves.
    outer: Vec<(Table, Vec<Value>)>,
    /// The client set `CLIENT_FOUND_ROWS` (Django does): an UPDATE reports
    /// the rows it matched, not only the ones it changed.
    pub found_rows: bool,
    /// A recursive CTE's rows from the previous round, by name, for its
    /// step's `Plan::CteRef`.
    cte_rows: std::collections::HashMap<String, Vec<Vec<Value>>>,
}

impl Executor {
    pub fn new(db: Arc<Mutex<DbState>>, current_db: Option<String>) -> Self {
        Self {
            db,
            current_db,
            params: Vec::new(),
            last_affected_rows: 0,
            last_insert_id: 0,
            last_found_rows: 0,
            insert_row: None,
            session_insert_id: 0,
            sql_mode: Default::default(),
            autocommit: true,
            writing: std::cell::Cell::new(false),
            outer: Vec::new(),
            found_rows: false,
            cte_rows: std::collections::HashMap::new(),
        }
    }

    /// Finds the `Table` a plan's rows ultimately come from, for resolving
    /// `Expr::ColName` by name in `Filter`/`Project`. Looks through any
    /// chain of single-source wrapper nodes (`Filter`, `Project`) down to
    /// the underlying `Scan` — a bare `match` on `Plan::Scan` alone missed
    /// this for anything with a `WHERE` clause, since that wraps the scan
    /// in `Plan::Filter` first, silently resolving every column reference
    /// to `Value::Null` instead of erroring or working.
    fn resolve_table_context(&self, plan: &Plan) -> Result<Option<Table>, MySqlError> {
        match plan {
            Plan::Scan { db, table, alias } => {
                let mut t = self.load_table(db, table)?;
                // Found via a differential test against real MySQL before a
                // public release: joins qualified columns by table name
                // only, so `oi.product_id` (alias `oi`) never matched and
                // fell back to the *other* table's `product_id` -- turning
                // `JOIN ... ON oi.product_id = p.product_id` into a
                // cartesian product.
                if let Some(a) = alias {
                    t.name = a.clone();
                }
                Ok(Some(t))
            }
            Plan::Filter { source, .. } => self.resolve_table_context(source),
            Plan::Project { source, .. } => self.resolve_table_context(source),
            Plan::Finish { source, .. } => self.resolve_table_context(source),
            Plan::Derived { alias, .. } | Plan::CteRef { alias, .. } => {
                let names = {
                    let state = self.db.lock().unwrap();
                    crate::mysql::plan::column_names(plan, &state)
                };
                Ok(Some(derived_table(alias, &names)))
            }
            Plan::Join { left, right, .. } => {
                let l = self.resolve_table_context(left)?;
                let r = self.resolve_table_context(right)?;
                Ok(merge_table_contexts(l, r))
            }
            _ => Ok(None),
        }
    }

    /// Runs a subquery for the current row of the enclosing query, which
    /// its correlated column references read.
    fn run_subquery(
        &self,
        plan: &Plan,
        row: &[Value],
        table: Option<&Table>,
    ) -> Result<Vec<Vec<Value>>, MySqlError> {
        let mut child = Executor::new(self.db.clone(), self.current_db.clone());
        child.params = self.params.clone();
        child.sql_mode = self.sql_mode.clone();
        child.autocommit = self.autocommit;
        child.session_insert_id = self.session_insert_id;
        child.cte_rows = self.cte_rows.clone();
        child.outer = self.outer.clone();
        if let Some(t) = table {
            child.outer.push((Table::new(t.name.clone(), t.columns.clone()), row.to_vec()));
        }
        child.execute_plan(plan.clone())
    }

    /// An enclosing query's column, for a correlated subquery.
    fn outer_column(&self, name: &str) -> Result<Option<Value>, MySqlError> {
        for (t, row) in self.outer.iter().rev() {
            if let Some(i) = resolve_column(t, name)? {
                return Ok(Some(row.get(i).cloned().unwrap_or(Value::Null)));
            }
        }
        Ok(None)
    }

    pub fn execute_plan(&mut self, plan: Plan) -> Result<Vec<Vec<Value>>, MySqlError> {
        match plan {
            Plan::Dummy => Ok(vec![vec![]]),
            // Found via testing before a public release: this used to be a
            // fixed list, so a `CREATE DATABASE` never showed up in it.
            Plan::ShowDatabases => {
                let state = self.db.lock().unwrap();
                Ok(state.schemas.keys().map(|s| vec![Value::Text(s.clone())]).collect())
            }
            Plan::Use(db) => {
                let state = self.db.lock().unwrap();
                if !state.schemas.contains_key(&db) {
                    return Err(MySqlError::new(
                        1049,
                        "42000",
                        format!("Unknown database '{}'", db),
                    ));
                }
                self.current_db = Some(db);
                Ok(vec![])
            }
            Plan::ShowTables { db, like, full } => {
                let state = self.db.lock().unwrap();
                let schema = state.schemas.get(&db).ok_or_else(|| {
                    MySqlError::new(1049, "42000", format!("Unknown database '{}'", db))
                })?;
                let mut rows = Vec::new();
                for table_name in schema.tables.keys() {
                    if let Some(p) = &like
                        && !mysql_like(table_name, p, Some('\\'))
                    {
                        continue;
                    }
                    let mut row = vec![Value::Text(table_name.clone())];
                    if full {
                        row.push(Value::Text("BASE TABLE".into()));
                    }
                    rows.push(row);
                }
                Ok(rows)
            }
            Plan::ShowColumns { db, table } => {
                let t = self.load_table(&db, &table)?;
                let keys = t.keys();
                let mut rows = Vec::new();
                for (i, col) in t.columns.iter().enumerate() {
                    // MySQL's Key column: PRI, else UNI for a single-column
                    // unique key, else MUL for the first column of any other
                    // key.
                    let key = if col.primary_key {
                        "PRI"
                    } else if keys.iter().any(|(_, c)| c.len() == 1 && c[0] == i) {
                        "UNI"
                    } else if keys.iter().any(|(_, c)| c[0] == i) {
                        "MUL"
                    } else {
                        ""
                    };
                    let extra = if col.auto_increment {
                        "auto_increment"
                    } else if col.default_now && col.on_update_now {
                        "DEFAULT_GENERATED on update CURRENT_TIMESTAMP"
                    } else if col.default_now {
                        "DEFAULT_GENERATED"
                    } else {
                        ""
                    };
                    rows.push(vec![
                        Value::Text(col.name.clone()),
                        Value::Text(mysql_type_name(&col.ty)),
                        Value::Text(if col.not_null { "NO" } else { "YES" }.to_string()),
                        Value::Text(key.to_string()),
                        column_default_text(col).map(Value::Text).unwrap_or(Value::Null),
                        Value::Text(extra.to_string()),
                    ]);
                }
                Ok(rows)
            }
            Plan::ShowCreateTable { db, table } => {
                let t = self.load_table(&db, &table)?;
                let mut lines = Vec::new();
                for col in &t.columns {
                    let mut l = format!("  `{}` {}", col.name, mysql_type_name(&col.ty));
                    if col.not_null {
                        l.push_str(" NOT NULL");
                    }
                    if col.auto_increment {
                        l.push_str(" AUTO_INCREMENT");
                    } else if let Some(d) = column_default_text(col) {
                        if col.default_now {
                            l.push_str(&format!(" DEFAULT {d}"));
                        } else {
                            l.push_str(&format!(" DEFAULT '{}'", d.replace('\'', "''")));
                        }
                    } else if !col.not_null {
                        l.push_str(" DEFAULT NULL");
                    }
                    if col.on_update_now {
                        l.push_str(" ON UPDATE CURRENT_TIMESTAMP");
                    }
                    lines.push(l);
                }
                let quote = |cols: &[usize]| {
                    cols.iter()
                        .map(|&c| format!("`{}`", t.columns[c].name))
                        .collect::<Vec<_>>()
                        .join(",")
                };
                for (name, cols) in t.keys() {
                    if name == "PRIMARY" {
                        lines.push(format!("  PRIMARY KEY ({})", quote(&cols)));
                    } else {
                        lines.push(format!("  UNIQUE KEY `{name}` ({})", quote(&cols)));
                    }
                }
                let sql = format!(
                    "CREATE TABLE `{}` (\n{}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci",
                    t.name,
                    lines.join(",\n")
                );
                Ok(vec![vec![Value::Text(t.name.clone()), Value::Text(sql)]])
            }
            Plan::CreateTable { db, table, columns, unique_keys, if_not_exists } => {
                let mut state = self.db.lock().unwrap();
                let schema = state.schemas.get_mut(&db).ok_or_else(|| {
                    MySqlError::new(1049, "42000", format!("Unknown database '{}'", db))
                })?;
                // Found via testing before a public release: IF NOT EXISTS
                // was ignored, so every migration tool's second run failed.
                if if_not_exists && schema.tables.contains_key(&table) {
                    return Ok(vec![]);
                }
                if schema.tables.contains_key(&table) {
                    return Err(MySqlError::new(
                        1050,
                        "42S01",
                        format!("Table '{}' already exists", table),
                    ));
                }
                let mut t = Table::new(table.clone(), columns);
                t.unique_keys = unique_keys;
                schema.tables.insert(table, Arc::new(t));
                Ok(vec![])
            }
            Plan::DropTable { tables, if_exists } => {
                let mut state = self.db.lock().unwrap();
                let missing: Vec<String> = tables
                    .iter()
                    .filter(|(db, t)| {
                        !state.schemas.get(db).is_some_and(|s| s.tables.contains_key(t))
                    })
                    .map(|(db, t)| format!("{db}.{t}"))
                    .collect();
                if !missing.is_empty() && !if_exists {
                    return Err(MySqlError::new(
                        1051,
                        "42S02",
                        format!("Unknown table '{}'", missing.join(",")),
                    ));
                }
                for (db, t) in &tables {
                    if let Some(schema) = state.schemas.get_mut(db) {
                        schema.tables.remove(t);
                    }
                }
                Ok(vec![])
            }
            Plan::Truncate { db, table } => {
                let mut state = self.db.lock().unwrap();
                let schema = state.schemas.get_mut(&db).ok_or_else(|| {
                    MySqlError::new(1049, "42000", format!("Unknown database '{}'", db))
                })?;
                let t = schema
                    .tables
                    .get_mut(&table)
                    .ok_or_else(|| MySqlError::unknown_table(&table))?;
                let t_mut = Arc::make_mut(t);
                t_mut.rows.clear();
                t_mut.next_auto_increment = 1;
                Ok(vec![])
            }
            Plan::DropDatabase { name, if_exists } => {
                let mut state = self.db.lock().unwrap();
                if name.eq_ignore_ascii_case("information_schema") {
                    return Err(MySqlError::new(
                        1044,
                        "42000",
                        "Access denied for user 'root'@'localhost' to database 'information_schema'",
                    ));
                }
                if state.schemas.remove(&name).is_none() && !if_exists {
                    return Err(MySqlError::new(
                        1008,
                        "HY000",
                        format!("Can't drop database '{name}'; database doesn't exist"),
                    ));
                }
                if self.current_db.as_deref() == Some(name.as_str()) {
                    self.current_db = None;
                }
                Ok(vec![])
            }
            Plan::CreateDatabase { name, if_not_exists } => {
                let mut state = self.db.lock().unwrap();
                if state.schemas.contains_key(&name) {
                    if if_not_exists {
                        return Ok(vec![]);
                    }
                    return Err(MySqlError::new(
                        1007,
                        "HY000",
                        format!("Can't create database '{name}'; database exists"),
                    ));
                }
                state.schemas.insert(name, crate::mysql::catalog::Schema::default());
                Ok(vec![])
            }
            Plan::CreateIndex { db, table, columns, if_not_exists, unique } => {
                let mut t = match self.load_table(&db, &table) {
                    Ok(t) => t,
                    Err(_) if if_not_exists => return Ok(vec![]),
                    Err(e) => return Err(e),
                };
                for col in &columns {
                    if resolve_column_index(&t.columns, col).is_none() {
                        return Err(MySqlError::new(
                            1072,
                            "42000",
                            format!("Key column '{col}' doesn't exist in table"),
                        ));
                    }
                }
                if let Some(name) = unique {
                    add_unique_key(&mut t, UniqueKey { name, columns })?;
                    self.store_table(&db, t)?;
                }
                Ok(vec![])
            }
            Plan::AlterTable { db, table, ops } => {
                let mut t = self.load_table(&db, &table)?;
                let mut rename_to = None;
                for op in ops {
                    alter_table(&mut t, op, &mut rename_to, &self.sql_mode)?;
                }
                let mut state = self.db.lock().unwrap();
                let schema = state.schemas.get_mut(&db).ok_or_else(|| {
                    MySqlError::new(1049, "42000", format!("Unknown database '{}'", db))
                })?;
                if let Some(new) = rename_to {
                    if schema.tables.contains_key(&new) {
                        return Err(MySqlError::new(
                            1050,
                            "42S01",
                            format!("Table '{new}' already exists"),
                        ));
                    }
                    schema.tables.remove(&table);
                    t.name = new;
                }
                schema.tables.insert(t.name.clone(), Arc::new(t));
                Ok(vec![])
            }
            Plan::Insert { db, table, columns, rows, mode } => {
                let mut work = self.load_table(&db, &table)?;
                let counter_before = work.next_auto_increment;
                let result = (|| -> Result<Vec<Vec<Value>>, MySqlError> {
                    let keys = work.keys();
                    let mut affected = 0u64;
                    let mut first_generated_id: Option<i64> = None;

                    let mut col_indices = Vec::new();
                    if columns.is_empty() {
                        col_indices.extend(0..work.columns.len());
                    } else {
                        for col_name in &columns {
                            let idx = resolve_column_index(&work.columns, col_name)
                                .ok_or_else(|| MySqlError::unknown_column(col_name))?;
                            col_indices.push(idx);
                        }
                    }

                    for (row_no, row_exprs) in rows.iter().enumerate() {
                        if row_exprs.len() != col_indices.len() {
                            return Err(MySqlError::new(
                                1136,
                                "21S01",
                                format!(
                                    "Column count doesn't match value count at row {}",
                                    row_no + 1
                                ),
                            ));
                        }
                        let mut new_row = vec![Value::Null; work.columns.len()];
                        let mut provided = vec![false; work.columns.len()];
                        for (i, expr) in row_exprs.iter().enumerate() {
                            self.writing.set(true);
                            let v = self.eval_expr(expr, &[], None);
                            self.writing.set(false);
                            new_row[col_indices[i]] = v?;
                            provided[col_indices[i]] = true;
                        }

                        let now = now_ts();
                        for (i, col) in work.columns.iter().enumerate() {
                            // MySQL generates an id for NULL *and* for 0 in an
                            // AUTO_INCREMENT column (default sql_mode).
                            if col.auto_increment
                                && (new_row[i].is_null() || new_row[i] == Value::Int(0))
                            {
                                new_row[i] = Value::Int(work.next_auto_increment);
                                first_generated_id.get_or_insert(work.next_auto_increment);
                                work.next_auto_increment += 1;
                            } else if provided[i] {
                                // Found via testing before a public release: an
                                // explicit NULL used to be replaced by the
                                // column's DEFAULT. MySQL only uses the default
                                // for an omitted column; an explicit NULL stays
                                // NULL, or is an error in a NOT NULL column.
                                if new_row[i].is_null() && col.not_null {
                                    return Err(column_cannot_be_null(&col.name));
                                }
                            } else if new_row[i].is_null() {
                                if col.default_now {
                                    new_row[i] = Value::Ts(now);
                                } else if let Some(def) = &col.default {
                                    new_row[i] = def.clone();
                                } else if col.not_null {
                                    // Strict mode: an error. Otherwise MySQL
                                    // uses the type's implicit default (0, '',
                                    // the zero date).
                                    if self.sql_mode.strict() {
                                        return Err(MySqlError::new(
                                            1364,
                                            "HY000",
                                            format!(
                                                "Field '{}' doesn't have a default value",
                                                col.name
                                            ),
                                        ));
                                    }
                                    new_row[i] = added_column_value(col);
                                }
                            }
                        }

                        // Store every value as its column's declared type (see
                        // `coerce_to_column`), the way real MySQL converts on
                        // write -- not as whatever shape the literal happened to
                        // arrive in.
                        for (i, col) in work.columns.iter().enumerate() {
                            let v = std::mem::replace(&mut new_row[i], Value::Null);
                            new_row[i] = coerce_to_column(v, col, &self.sql_mode)?;
                            if col.auto_increment
                                && let Value::Int(n) = new_row[i]
                                && n >= work.next_auto_increment
                            {
                                // An explicit id moves the counter past it, so the
                                // next generated id can't collide with it.
                                work.next_auto_increment = n + 1;
                            }
                        }

                        let conflict = find_key_conflict(&work, &keys, &new_row, None);
                        match (&mode, conflict) {
                            (_, None) => {
                                work.rows.push(new_row);
                                affected += 1;
                            }
                            (InsertMode::Error, Some((_, k))) => {
                                return Err(duplicate_key_error(&work, &keys[k], &new_row));
                            }
                            (InsertMode::Ignore, Some(_)) => {}
                            (InsertMode::Replace, Some(_)) => {
                                while let Some((i, _)) =
                                    find_key_conflict(&work, &keys, &new_row, None)
                                {
                                    work.rows.remove(i);
                                    affected += 1;
                                }
                                work.rows.push(new_row);
                                affected += 1;
                            }
                            (InsertMode::Upsert(assignments), Some((i, _))) => {
                                let before = work.rows[i].clone();
                                self.insert_row = Some(new_row);
                                let res = self.apply_assignments(&mut work, i, assignments);
                                self.insert_row = None;
                                res?;
                                if let Some((_, k)) =
                                    find_key_conflict(&work, &keys, &work.rows[i], Some(i))
                                {
                                    return Err(duplicate_key_error(
                                        &work,
                                        &keys[k],
                                        &work.rows[i],
                                    ));
                                }
                                // MySQL: 2 for an updated row; one the update
                                // left as it was is 0 (1 with FOUND_ROWS).
                                if work.rows[i] != before {
                                    affected += 2;
                                } else if self.found_rows {
                                    affected += 1;
                                }
                            }
                        }
                    }

                    self.store_table(&db, work.clone())?;
                    self.last_affected_rows = affected;
                    self.last_insert_id = first_generated_id.map(|v| v as u64).unwrap_or(0);
                    Ok(vec![])
                })();
                // A failed INSERT still consumes the AUTO_INCREMENT ids it
                // generated, as in InnoDB (the next row doesn't reuse them).
                if result.is_err() && work.next_auto_increment > counter_before {
                    let mut state = self.db.lock().unwrap();
                    if let Some(t) =
                        state.schemas.get_mut(&db).and_then(|s| s.tables.get_mut(&table))
                    {
                        Arc::make_mut(t).next_auto_increment = work.next_auto_increment;
                    }
                }
                result
            }
            Plan::Update { db, table, assignments, selection, order, limit } => {
                let mut work = self.load_table(&db, &table)?;
                let keys = work.keys();
                let targets =
                    self.dml_targets(&work, selection.as_ref(), &order, limit.as_ref())?;
                let mut changed = 0u64;
                for &i in &targets {
                    let before = work.rows[i].clone();
                    self.apply_assignments(&mut work, i, &assignments)?;
                    if let Some((_, k)) = find_key_conflict(&work, &keys, &work.rows[i], Some(i)) {
                        return Err(duplicate_key_error(&work, &keys[k], &work.rows[i]));
                    }
                    if work.rows[i] != before {
                        changed += 1;
                    }
                }
                self.store_table(&db, work)?;
                // MySQL reports the rows an UPDATE changed; with the
                // client's FOUND_ROWS flag, the rows it matched.
                self.last_affected_rows =
                    if self.found_rows { targets.len() as u64 } else { changed };
                Ok(vec![])
            }
            Plan::Delete { db, table, selection, order, limit } => {
                let mut work = self.load_table(&db, &table)?;
                let targets =
                    self.dml_targets(&work, selection.as_ref(), &order, limit.as_ref())?;
                let mut keep = vec![true; work.rows.len()];
                for &i in &targets {
                    keep[i] = false;
                }
                let mut k = keep.iter();
                work.rows.retain(|_| *k.next().unwrap());
                self.store_table(&db, work)?;
                self.last_affected_rows = targets.len() as u64;
                Ok(vec![])
            }
            Plan::Scan { db, table, .. } => Ok(self.load_table(&db, &table)?.rows),
            Plan::Derived { plan, .. } => self.execute_plan(*plan),
            Plan::InsertSelect { insert, query } => {
                // The SELECT runs first, over the table as it was (so
                // `INSERT INTO t SELECT ... FROM t` doesn't see its own rows).
                let rows = self.execute_plan(*query)?;
                let Plan::Insert { db, table, columns, mode, .. } = *insert else {
                    unreachable!("InsertSelect always wraps an Insert")
                };
                let rows =
                    rows.into_iter().map(|r| r.into_iter().map(Expr::Const).collect()).collect();
                self.execute_plan(Plan::Insert { db, table, columns, rows, mode })
            }
            Plan::CteRef { name, .. } => Ok(self.cte_rows.get(&name).cloned().unwrap_or_default()),
            Plan::SetOp { op, all, left, right } => {
                let width = |p: &Plan, rows: &[Vec<Value>]| {
                    crate::mysql::plan::static_names(p)
                        .map(|n| n.len())
                        .or_else(|| rows.first().map(|r| r.len()))
                };
                let (lw, rw) = (left.clone(), right.clone());
                let l = self.execute_plan(*left)?;
                let r = self.execute_plan(*right)?;
                if let (Some(a), Some(b)) = (width(&lw, &l), width(&rw, &r))
                    && a != b
                {
                    return Err(MySqlError::new(
                        1222,
                        "21000",
                        "The used SELECT statements have a different number of columns",
                    ));
                }
                Ok(set_op(op, all, l, r))
            }
            Plan::RecursiveCte { name, anchor, step, all, .. } => {
                let mut rows = self.execute_plan(*anchor)?;
                if !all {
                    rows = set_op(SetOpKind::Union, false, rows, Vec::new());
                }
                let mut frontier = rows.clone();
                let mut rounds = 0;
                let saved = self.cte_rows.remove(&name);
                while !frontier.is_empty() {
                    rounds += 1;
                    if rounds > 1000 {
                        return Err(MySqlError::new(
                            3636,
                            "HY000",
                            "Recursive query aborted after 1001 iterations. Try increasing \
                             @@cte_max_recursion_depth to a larger value.",
                        ));
                    }
                    self.cte_rows.insert(name.clone(), frontier);
                    let mut new = self.execute_plan((*step).clone())?;
                    if !all {
                        new = set_op(SetOpKind::Union, false, new, Vec::new());
                        new.retain(|n| !rows.iter().any(|r| rows_distinct_equal(r, n)));
                    }
                    rows.extend(new.iter().cloned());
                    frontier = new;
                }
                self.cte_rows.remove(&name);
                if let Some(v) = saved {
                    self.cte_rows.insert(name, v);
                }
                Ok(rows)
            }
            Plan::Filter { source, predicate } => {
                let table_context = self.resolve_table_context(&source)?;

                let rows = self.execute_plan(*source)?;
                if rows.is_empty() {
                    check_columns(
                        std::iter::once(&predicate),
                        table_context.as_ref(),
                        &self.outer,
                    )?;
                }
                let mut out_rows = Vec::new();
                for row in rows {
                    let val = self.eval_expr(&predicate, &row, table_context.as_ref())?;
                    if !val.is_null() && val != Value::Int(0) {
                        out_rows.push(row);
                    }
                }
                Ok(out_rows)
            }
            Plan::Project { source, exprs, .. } => {
                let table_context = self.resolve_table_context(&source)?;

                let rows = self.execute_plan(*source)?;
                if rows.is_empty() {
                    check_columns(exprs.iter(), table_context.as_ref(), &self.outer)?;
                }
                let mut out_rows = Vec::new();
                for row in rows {
                    let mut out_row = Vec::new();
                    for expr in &exprs {
                        if matches!(expr, Expr::Wildcard) {
                            // Expands to every column of the current row,
                            // not one value -- see `Expr::Wildcard`'s own
                            // doc comment.
                            out_row.extend(row.iter().cloned());
                        } else {
                            out_row.push(self.eval_expr(expr, &row, table_context.as_ref())?);
                        }
                    }
                    out_rows.push(out_row);
                }
                Ok(out_rows)
            }
            Plan::Aggregate { source, group_exprs, exprs, having, .. } => {
                let table_context = self.resolve_table_context(&source)?;
                let rows = self.execute_plan(*source)?;
                if rows.is_empty() {
                    check_columns(exprs.iter(), table_context.as_ref(), &self.outer)?;
                }

                // Group rows by the evaluated GROUP BY key. `Value`'s
                // `PartialEq` (via `Vec<Value>`) is enough to compare keys
                // here — linear search per row is fine at this project's
                // "simple over performant, local-use only" scale. No
                // GROUP BY clause but an aggregate in the projection means
                // the whole input is a single implicit group (possibly
                // empty, e.g. `SELECT COUNT(*) FROM t` on an empty table).
                let mut groups: Vec<(Vec<Value>, Vec<Vec<Value>>)> = Vec::new();
                if group_exprs.is_empty() {
                    groups.push((Vec::new(), rows));
                } else {
                    for row in rows {
                        let key = group_exprs
                            .iter()
                            .map(|e| self.eval_expr(e, &row, table_context.as_ref()))
                            .collect::<Result<Vec<_>, _>>()?;
                        if let Some(g) = groups.iter_mut().find(|(k, _)| *k == key) {
                            g.1.push(row);
                        } else {
                            groups.push((key, vec![row]));
                        }
                    }
                }

                let mut out_rows = Vec::new();
                for (_key, group_rows) in &groups {
                    if let Some(having) = &having {
                        let val =
                            self.eval_group_expr(having, group_rows, table_context.as_ref())?;
                        if val.is_null() || val == Value::Int(0) {
                            continue;
                        }
                    }
                    let mut out_row = Vec::new();
                    for expr in &exprs {
                        out_row.push(self.eval_group_expr(
                            expr,
                            group_rows,
                            table_context.as_ref(),
                        )?);
                    }
                    out_rows.push(out_row);
                }
                Ok(out_rows)
            }
            Plan::Finish { source, order, hidden, distinct, limit, offset, calc_found_rows } => {
                let limit = limit.map(|e| self.count(&e)).transpose()?;
                let offset = offset.map(|e| self.count(&e)).transpose()?;
                let mut rows = self.execute_plan(*source)?;
                let key_index = |row: &[Value], key: &SortKey| match key {
                    SortKey::Output(i) => *i,
                    SortKey::Hidden(j) => row.len() - hidden + j,
                };
                for (key, _) in &order {
                    if let (SortKey::Output(i), Some(row)) = (key, rows.first())
                        && *i >= row.len() - hidden
                    {
                        return Err(MySqlError::new(
                            1054,
                            "42S22",
                            format!("Unknown column '{}' in 'order clause'", i + 1),
                        ));
                    }
                }
                if !order.is_empty() {
                    // Stable, so rows equal on every key keep their order.
                    rows.sort_by(|a, b| {
                        for (key, asc) in &order {
                            let (ia, ib) = (key_index(a, key), key_index(b, key));
                            let ord = sort_cmp(&a[ia], &b[ib]);
                            let ord = if *asc { ord } else { ord.reverse() };
                            if ord != Ordering::Equal {
                                return ord;
                            }
                        }
                        Ordering::Equal
                    });
                }
                if distinct {
                    // Duplicates are judged on the visible columns only; the
                    // first (i.e. best-sorted) occurrence of each is kept.
                    let mut kept: Vec<Vec<Value>> = Vec::with_capacity(rows.len());
                    for row in rows {
                        let visible = row.len() - hidden;
                        if !kept.iter().any(|k| rows_distinct_equal(&k[..visible], &row[..visible]))
                        {
                            kept.push(row);
                        }
                    }
                    rows = kept;
                }
                if calc_found_rows {
                    self.last_found_rows = rows.len() as u64;
                }
                let start = offset.unwrap_or(0) as usize;
                let mut rows: Vec<Vec<Value>> = rows.into_iter().skip(start).collect();
                if let Some(limit) = limit {
                    rows.truncate(limit as usize);
                }
                if hidden > 0 {
                    for row in rows.iter_mut() {
                        row.truncate(row.len() - hidden);
                    }
                }
                Ok(rows)
            }
            Plan::Join { left, right, op } => {
                // Found via testing before a public release: every join's
                // ON condition used to be evaluated with no table context
                // at all (`eval_expr(&cond, &row, None)`), so every column
                // reference inside it resolved to NULL unconditionally --
                // meaning the condition was always NULL, never true, and
                // every single JOIN (of any kind) silently returned the
                // wrong result (INNER: always empty; LEFT: always every
                // left row with the right side all-NULL) with no error at
                // all. Resolving column names needs *both* sides' columns
                // in scope, concatenated the same way the row itself is
                // (`left columns ++ right columns`), not just one table's.
                let l_table = self.resolve_table_context(&left)?;
                let r_table = self.resolve_table_context(&right)?;
                let join_table = merge_table_contexts(l_table, r_table);
                let l_rows = self.execute_plan(*left)?;
                let r_rows = self.execute_plan(*right)?;
                let mut out_rows = Vec::new();

                match op {
                    JoinOp::Cross => {
                        for l in &l_rows {
                            for r in &r_rows {
                                let mut row = l.clone();
                                row.extend(r.clone());
                                out_rows.push(row);
                            }
                        }
                    }
                    JoinOp::Inner(cond) => {
                        for l in &l_rows {
                            for r in &r_rows {
                                let mut row = l.clone();
                                row.extend(r.clone());
                                let val = self.eval_expr(&cond, &row, join_table.as_ref())?;
                                if !val.is_null() && val != Value::Int(0) {
                                    out_rows.push(row);
                                }
                            }
                        }
                    }
                    JoinOp::Left(cond) => {
                        let r_len = if r_rows.is_empty() { 0 } else { r_rows[0].len() };
                        for l in &l_rows {
                            let mut matched = false;
                            for r in &r_rows {
                                let mut row = l.clone();
                                row.extend(r.clone());
                                let val = self.eval_expr(&cond, &row, join_table.as_ref())?;
                                if !val.is_null() && val != Value::Int(0) {
                                    out_rows.push(row);
                                    matched = true;
                                }
                            }
                            if !matched {
                                let mut row = l.clone();
                                row.extend(vec![Value::Null; r_len]);
                                out_rows.push(row);
                            }
                        }
                    }
                }
                Ok(out_rows)
            }
        }
    }

    /// A LIMIT/OFFSET value: a literal, or a bound `?` (drivers send it as
    /// an integer or a numeric string).
    fn count(&self, e: &Expr) -> Result<u64, MySqlError> {
        match self.eval_expr(e, &[], None)? {
            Value::Int(n) if n >= 0 => Ok(n as u64),
            Value::Text(t) if t.trim().parse::<u64>().is_ok() => Ok(t.trim().parse().unwrap()),
            v => Err(MySqlError::new(
                1210,
                "HY000",
                format!("Incorrect arguments to LIMIT: {}", render_text(&v)),
            )),
        }
    }

    fn load_table(&self, db: &str, table: &str) -> Result<Table, MySqlError> {
        let state = self.db.lock().unwrap();
        if let Some(t) = crate::mysql::infoschema::lookup_table(&state, db, table) {
            return Ok((*t).clone());
        }
        if !state.schemas.contains_key(db) {
            return Err(MySqlError::new(1049, "42000", format!("Unknown database '{}'", db)));
        }
        Err(MySqlError::unknown_table(table))
    }

    fn store_table(&self, db: &str, t: Table) -> Result<(), MySqlError> {
        if db.eq_ignore_ascii_case("information_schema") {
            return Err(MySqlError::new(
                1044,
                "42000",
                "Access denied for user 'root'@'localhost' to database 'information_schema'",
            ));
        }
        let mut state = self.db.lock().unwrap();
        let schema = state
            .schemas
            .get_mut(db)
            .ok_or_else(|| MySqlError::new(1049, "42000", format!("Unknown database '{}'", db)))?;
        schema.tables.insert(t.name.clone(), Arc::new(t));
        Ok(())
    }

    /// The rows an UPDATE/DELETE acts on, in the order it acts on them:
    /// those matching WHERE, sorted by ORDER BY, cut to LIMIT.
    fn dml_targets(
        &self,
        t: &Table,
        selection: Option<&Expr>,
        order: &[(Expr, bool)],
        limit: Option<&Expr>,
    ) -> Result<Vec<usize>, MySqlError> {
        let limit = limit.map(|e| self.count(e)).transpose()?;
        let mut targets = Vec::new();
        for (i, row) in t.rows.iter().enumerate() {
            if let Some(sel) = selection {
                let v = self.eval_expr(sel, row, Some(t))?;
                if v.is_null() || v == Value::Int(0) {
                    continue;
                }
            }
            targets.push(i);
        }
        if !order.is_empty() {
            let mut keyed = Vec::with_capacity(targets.len());
            for i in targets {
                let mut k = Vec::with_capacity(order.len());
                for (e, _) in order {
                    k.push(self.eval_expr(e, &t.rows[i], Some(t))?);
                }
                keyed.push((k, i));
            }
            keyed.sort_by(|(a, _), (b, _)| {
                for (n, (_, asc)) in order.iter().enumerate() {
                    let o = sort_cmp(&a[n], &b[n]);
                    let o = if *asc { o } else { o.reverse() };
                    if o != Ordering::Equal {
                        return o;
                    }
                }
                Ordering::Equal
            });
            targets = keyed.into_iter().map(|(_, i)| i).collect();
        }
        if let Some(n) = limit {
            targets.truncate(n as usize);
        }
        Ok(targets)
    }

    /// Applies `SET` assignments to row `i`, one at a time, left to right:
    /// MySQL's own single-table UPDATE semantics, where a later assignment
    /// sees an earlier one's new value (`SET a = a + 1, b = a` sets b to the
    /// new a). An `ON UPDATE CURRENT_TIMESTAMP` column the statement didn't
    /// assign itself is set to now.
    fn apply_assignments(
        &self,
        t: &mut Table,
        i: usize,
        assignments: &[(String, Expr)],
    ) -> Result<(), MySqlError> {
        let before = t.rows[i].clone();
        let mut assigned = Vec::with_capacity(assignments.len());
        for (col_name, expr) in assignments {
            let idx = resolve_column_index(&t.columns, col_name)
                .ok_or_else(|| MySqlError::unknown_column(col_name))?;
            self.writing.set(true);
            let val = self.eval_expr(expr, &t.rows[i], Some(&*t));
            self.writing.set(false);
            let val = val?;
            let col = &t.columns[idx];
            if val.is_null() && col.not_null {
                return Err(column_cannot_be_null(&col.name));
            }
            t.rows[i][idx] = coerce_to_column(val, col, &self.sql_mode)?;
            assigned.push(idx);
        }
        // ON UPDATE CURRENT_TIMESTAMP only moves when something else in
        // the row actually changed, as in MySQL.
        if t.rows[i] != before {
            let now = now_ts();
            for idx in 0..t.columns.len() {
                if t.columns[idx].on_update_now && !assigned.contains(&idx) {
                    t.rows[i][idx] = Value::Ts(now);
                }
            }
        }
        Ok(())
    }

    fn eval_expr(
        &self,
        expr: &Expr,
        row: &[Value],
        table: Option<&Table>,
    ) -> Result<Value, MySqlError> {
        match expr {
            Expr::Const(v) => Ok(v.clone()),
            Expr::Param(i) => Ok(self.params.get(*i).cloned().unwrap_or(Value::Null)),
            Expr::Col(i) => Ok(row.get(*i).cloned().unwrap_or(Value::Null)),
            Expr::FoundRows => Ok(Value::Int(self.last_found_rows as i64)),
            Expr::ColName(name) => match table {
                Some(t) => match resolve_column(t, name)? {
                    Some(idx) => Ok(row.get(idx).cloned().unwrap_or(Value::Null)),
                    None => match self.outer_column(name)? {
                        Some(v) => Ok(v),
                        // Found via testing before a public release: a
                        // mistyped column used to evaluate to NULL, so
                        // `WHERE nosuch = 1` silently matched nothing
                        // instead of erroring.
                        None => Err(MySqlError::new(
                            1054,
                            "42S22",
                            format!("Unknown column '{name}' in 'field list'"),
                        )),
                    },
                },
                None => Ok(self.outer_column(name)?.unwrap_or(Value::Null)),
            },
            Expr::Subquery(plan) => {
                let rows = self.run_subquery(plan, row, table)?;
                match rows.as_slice() {
                    [] => Ok(Value::Null),
                    [r] => {
                        if r.len() != 1 {
                            return Err(MySqlError::new(
                                1241,
                                "21000",
                                "Operand should contain 1 column(s)",
                            ));
                        }
                        Ok(r[0].clone())
                    }
                    _ => Err(MySqlError::new(1242, "21000", "Subquery returns more than 1 row")),
                }
            }
            Expr::InSubquery { expr, plan, negated } => {
                let l = self.eval_expr(expr, row, table)?;
                let rows = self.run_subquery(plan, row, table)?;
                if rows.first().is_some_and(|r| r.len() != 1) {
                    return Err(MySqlError::new(
                        1241,
                        "21000",
                        "Operand should contain 1 column(s)",
                    ));
                }
                let items: Vec<Value> = rows.into_iter().map(|mut r| r.swap_remove(0)).collect();
                if items.is_empty() {
                    // Nothing to match, so even `NULL IN (empty)` is false.
                    return Ok(Value::Int(i64::from(*negated)));
                }
                eval_in_list(l, &items, *negated)
            }
            Expr::Quantified { op, expr, plan, all } => {
                let l = self.eval_expr(expr, row, table)?;
                let rows = self.run_subquery(plan, row, table)?;
                if rows.first().is_some_and(|r| r.len() != 1) {
                    return Err(MySqlError::new(
                        1241,
                        "21000",
                        "Operand should contain 1 column(s)",
                    ));
                }
                // ALL: true unless some comparison is false (true for no
                // rows); ANY: true if some comparison is true. Otherwise a
                // NULL comparison makes the result NULL.
                let mut saw_null = false;
                for r in rows {
                    let v =
                        eval_compare(*op, l.clone(), r.into_iter().next().unwrap_or(Value::Null))?;
                    match v {
                        Value::Null => saw_null = true,
                        Value::Int(0) if *all => return Ok(Value::Int(0)),
                        Value::Int(0) => {}
                        _ if !*all => return Ok(Value::Int(1)),
                        _ => {}
                    }
                }
                Ok(if saw_null { Value::Null } else { Value::Int(i64::from(*all)) })
            }
            Expr::Exists { plan, negated } => {
                let found = !self.run_subquery(plan, row, table)?.is_empty();
                Ok(Value::Int(i64::from(found != *negated)))
            }
            Expr::And(exprs) => {
                let mut res = Value::Int(1);
                for e in exprs {
                    let v = self.eval_expr(e, row, table)?;
                    if v.is_null() {
                        res = Value::Null;
                    } else if v == Value::Int(0) {
                        return Ok(Value::Int(0));
                    }
                }
                Ok(res)
            }
            Expr::Or(exprs) => {
                let mut res = Value::Int(0);
                for e in exprs {
                    let v = self.eval_expr(e, row, table)?;
                    if v == Value::Int(1) {
                        return Ok(Value::Int(1));
                    } else if v.is_null() {
                        res = Value::Null;
                    }
                }
                Ok(res)
            }
            Expr::Arith { op, left, right } => {
                let l = self.eval_expr(left, row, table)?;
                let r = self.eval_expr(right, row, table)?;
                // Division by zero is NULL, except in the values an INSERT/
                // UPDATE writes under strict ERROR_FOR_DIVISION_BY_ZERO.
                if matches!(op, ArithOp::Div | ArithOp::Mod)
                    && self.writing.get()
                    && self.sql_mode.strict()
                    && self.sql_mode.error_for_division_by_zero()
                    && !l.is_null()
                    && !r.is_null()
                    && value_to_f64(&r) == 0.0
                {
                    return Err(MySqlError::new(1365, "22012", "Division by 0"));
                }
                eval_arith(*op, l, r)
            }
            Expr::Compare { op, left, right } => {
                let l = self.eval_expr(left, row, table)?;
                let r = self.eval_expr(right, row, table)?;
                eval_compare(*op, l, r)
            }
            Expr::InList { expr, list, negated } => {
                let l = self.eval_expr(expr, row, table)?;
                let mut items = Vec::with_capacity(list.len());
                for item in list {
                    items.push(self.eval_expr(item, row, table)?);
                }
                eval_in_list(l, &items, *negated)
            }
            Expr::SysVar(name) => {
                let bare = name.rsplit('.').next().unwrap_or(name);
                if bare.eq_ignore_ascii_case("sql_mode") {
                    return Ok(Value::Text(self.sql_mode.as_str()));
                }
                if bare.eq_ignore_ascii_case("autocommit") {
                    return Ok(Value::Int(i64::from(self.autocommit)));
                }
                if name.eq_ignore_ascii_case("version") {
                    Ok(Value::Text("8.0.33".to_string()))
                } else if name.eq_ignore_ascii_case("version_comment") {
                    Ok(Value::Text("noida-db MySQL 8.0".to_string()))
                } else if name.eq_ignore_ascii_case("max_allowed_packet") {
                    Ok(Value::Int(67108864))
                } else if name.eq_ignore_ascii_case("lower_case_table_names") {
                    Ok(Value::Int(0))
                } else if name.eq_ignore_ascii_case("wait_timeout")
                    || name.eq_ignore_ascii_case("interactive_timeout")
                {
                    // Real MySQL default (seconds); client pools (e.g.
                    // mysql_async's connection setup probe) parse this as
                    // a number, so it can't be the empty-text fallback.
                    Ok(Value::Int(28800))
                } else if name.eq_ignore_ascii_case("socket") {
                    Ok(Value::Text("/tmp/mysql.sock".to_string()))
                } else {
                    // Everything else `SHOW VARIABLES` knows (`@@sql_mode`,
                    // `@@character_set_server`, `@@transaction_isolation`,
                    // ...), numbers as numbers; otherwise empty, never an
                    // error -- drivers probe many variables on connect.
                    let bare = name.rsplit('.').next().unwrap_or(name);
                    Ok(crate::mysql::engine::SESSION_VARIABLES
                        .iter()
                        .find(|(k, _)| k.eq_ignore_ascii_case(bare))
                        .map(|(_, v)| match v.parse::<i64>() {
                            Ok(n) => Value::Int(n),
                            Err(_) => Value::Text(v.to_string()),
                        })
                        .unwrap_or_else(|| Value::Text(String::new())))
                }
            }
            Expr::Not(e) => {
                let v = self.eval_expr(e, row, table)?;
                if v.is_null() {
                    Ok(Value::Null)
                } else if v == Value::Int(0) {
                    Ok(Value::Int(1))
                } else {
                    Ok(Value::Int(0))
                }
            }
            Expr::IsNull(e, negated) => {
                let v = self.eval_expr(e, row, table)?;
                let is_null = v.is_null();
                Ok(Value::Int((is_null != *negated) as i64))
            }
            Expr::Like { expr, pattern, escape, negated } => {
                let v = self.eval_expr(expr, row, table)?;
                let p = self.eval_expr(pattern, row, table)?;
                let esc = self.eval_expr(escape, row, table)?;
                if v.is_null() || p.is_null() {
                    return Ok(Value::Null);
                }
                let (Some(s), Some(pat)) = (value_as_text(&v), value_as_text(&p)) else {
                    return Ok(Value::Null);
                };
                let esc_char = value_as_text(&esc).and_then(|e| e.chars().next());
                let m = mysql_like(&s, &pat, esc_char);
                Ok(Value::Int((m != *negated) as i64))
            }
            Expr::Case { conditions, else_result } => {
                for (cond, result) in conditions {
                    let c = self.eval_expr(cond, row, table)?;
                    if !c.is_null() && c != Value::Int(0) {
                        return self.eval_expr(result, row, table);
                    }
                }
                match else_result {
                    Some(e) => self.eval_expr(e, row, table),
                    None => Ok(Value::Null),
                }
            }
            // Session-level functions need the connection's own state, not
            // just their arguments. SQLAlchemy calls `SELECT DATABASE()` on
            // connect; connection pools and admin tools call the rest.
            Expr::Call { name, .. } if name == "DATABASE" || name == "SCHEMA" => {
                Ok(self.current_db.clone().map(Value::Text).unwrap_or(Value::Null))
            }
            Expr::Call { name, .. }
                if matches!(
                    name.as_str(),
                    "USER" | "CURRENT_USER" | "SESSION_USER" | "SYSTEM_USER"
                ) =>
            {
                Ok(Value::Text("root@localhost".into()))
            }
            Expr::Call { name, args } if name == "VALUES" => {
                let (Some(new_row), Some(t), Some(Expr::ColName(c))) =
                    (&self.insert_row, table, args.first())
                else {
                    return Ok(Value::Null);
                };
                Ok(resolve_column_index(&t.columns, c)
                    .and_then(|i| new_row.get(i).cloned())
                    .unwrap_or(Value::Null))
            }
            Expr::Call { name, .. } if name == "CONNECTION_ID" => Ok(Value::Int(1)),
            Expr::Call { name, .. } if name == "LAST_INSERT_ID" => {
                Ok(Value::Int(self.session_insert_id as i64))
            }
            Expr::Call { name, .. } if name == "VERSION" => Ok(Value::Text("8.0.33".into())),
            Expr::Call { name, args } => {
                let vals: Vec<Value> =
                    args.iter().map(|a| self.eval_expr(a, row, table)).collect::<Result<_, _>>()?;
                eval_call(name, &vals)
            }
            _ => Err(MySqlError::unsupported("expr in execution")),
        }
    }

    /// Evaluates a projection expression against one group of rows
    /// (`Plan::Aggregate`'s output). Any `Expr::Agg` found — including
    /// nested inside arithmetic/boolean combinators, e.g. `COUNT(x) + 1`
    /// — is computed over the whole group; every other leaf expression
    /// (a bare grouped column, a literal, `?`, `@@var`) is evaluated
    /// against the group's first row, since a non-aggregated column in a
    /// `GROUP BY` query is only meaningful when it's constant within the
    /// group (matching every real column reference this binder produces:
    /// the `GROUP BY` key columns themselves).
    fn eval_group_expr(
        &self,
        expr: &Expr,
        rows: &[Vec<Value>],
        table: Option<&Table>,
    ) -> Result<Value, MySqlError> {
        // Compute every aggregate in `expr` over the whole group, splice the
        // results in as constants, then evaluate what's left once against
        // the group's first row. That works for any expression shape
        // (`COALESCE(SUM(x), 0)`, `CASE WHEN COUNT(*) > 1 ...`, `ROUND(AVG(x),
        // 2)`) instead of only the few combinators listed by hand before.
        let folded = self.fold_aggs(expr, rows, table)?;
        match rows.first() {
            Some(row) => self.eval_expr(&folded, row, table),
            None => self.eval_expr(&folded, &[], table),
        }
    }

    /// `expr` with each `Expr::Agg` replaced by its value over `rows`.
    /// `GROUP_CONCAT` over one group. `call` is the binder's
    /// `GROUP_CONCAT(value, separator, key1, asc1, key2, asc2, ...)`.
    fn group_concat(
        &self,
        call: &Expr,
        distinct: bool,
        rows: &[Vec<Value>],
        table: Option<&Table>,
    ) -> Result<Value, MySqlError> {
        let Expr::Call { args, .. } = call else {
            return Err(MySqlError::unsupported("GROUP_CONCAT shape"));
        };
        let sep = match args.get(1) {
            Some(Expr::Const(v)) => render_text(v),
            _ => ",".into(),
        };
        let order: Vec<(&Expr, bool)> = args[2..]
            .chunks(2)
            .map(|c| (&c[0], matches!(c.get(1), Some(Expr::Const(Value::Int(1))))))
            .collect();
        let mut items: Vec<(Vec<Value>, Value)> = Vec::new();
        for r in rows {
            let v = self.eval_expr(&args[0], r, table)?;
            if v.is_null() {
                continue;
            }
            if distinct && items.iter().any(|(_, u)| mysql_cmp(u, &v) == Some(Ordering::Equal)) {
                continue;
            }
            let keys =
                order.iter().map(|(e, _)| self.eval_expr(e, r, table)).collect::<Result<_, _>>()?;
            items.push((keys, v));
        }
        if items.is_empty() {
            return Ok(Value::Null);
        }
        items.sort_by(|(a, _), (b, _)| {
            for (n, (_, asc)) in order.iter().enumerate() {
                let o = sort_cmp(&a[n], &b[n]);
                let o = if *asc { o } else { o.reverse() };
                if o != Ordering::Equal {
                    return o;
                }
            }
            Ordering::Equal
        });
        let parts: Vec<String> = items.iter().map(|(_, v)| render_text(v)).collect();
        Ok(Value::Text(parts.join(&sep)))
    }

    fn fold_aggs(
        &self,
        expr: &Expr,
        rows: &[Vec<Value>],
        table: Option<&Table>,
    ) -> Result<Expr, MySqlError> {
        let f = |e: &Expr| self.fold_aggs(e, rows, table);
        let fb = |e: &Expr| -> Result<Box<Expr>, MySqlError> { Ok(Box::new(f(e)?)) };
        Ok(match expr {
            Expr::Agg { func, arg, distinct } => {
                if matches!(func, AggFunc::CountStar) {
                    return Ok(Expr::Const(Value::Int(rows.len() as i64)));
                }
                if let (AggFunc::GroupConcat, Some(arg)) = (func, arg) {
                    return Ok(Expr::Const(self.group_concat(arg, *distinct, rows, table)?));
                }
                let arg = arg
                    .as_ref()
                    .ok_or_else(|| MySqlError::unsupported("aggregate without argument"))?;
                let mut vals: Vec<Value> =
                    rows.iter().map(|r| self.eval_expr(arg, r, table)).collect::<Result<_, _>>()?;
                if *distinct {
                    // Found via testing before a public release: DISTINCT
                    // inside an aggregate was ignored (`COUNT(DISTINCT x)`
                    // counted every row).
                    let mut unique: Vec<Value> = Vec::with_capacity(vals.len());
                    for v in vals.into_iter().filter(|v| !v.is_null()) {
                        if !unique.iter().any(|u| mysql_cmp(u, &v) == Some(Ordering::Equal)) {
                            unique.push(v);
                        }
                    }
                    vals = unique;
                }
                Expr::Const(compute_agg(*func, &vals))
            }
            Expr::And(v) => Expr::And(v.iter().map(f).collect::<Result<_, _>>()?),
            Expr::Or(v) => Expr::Or(v.iter().map(f).collect::<Result<_, _>>()?),
            Expr::Compare { op, left, right } => {
                Expr::Compare { op: *op, left: fb(left)?, right: fb(right)? }
            }
            Expr::Arith { op, left, right } => {
                Expr::Arith { op: *op, left: fb(left)?, right: fb(right)? }
            }
            Expr::Call { name, args } => Expr::Call {
                name: name.clone(),
                args: args.iter().map(f).collect::<Result<_, _>>()?,
            },
            Expr::InList { expr, list, negated } => Expr::InList {
                expr: fb(expr)?,
                list: list.iter().map(f).collect::<Result<_, _>>()?,
                negated: *negated,
            },
            Expr::Not(x) => Expr::Not(fb(x)?),
            Expr::IsNull(x, neg) => Expr::IsNull(fb(x)?, *neg),
            Expr::Like { expr, pattern, escape, negated } => Expr::Like {
                expr: fb(expr)?,
                pattern: fb(pattern)?,
                escape: fb(escape)?,
                negated: *negated,
            },
            Expr::Case { conditions, else_result } => Expr::Case {
                conditions: conditions.iter().map(|(c, r)| Ok((f(c)?, f(r)?))).collect::<Result<
                    _,
                    MySqlError,
                >>(
                )?,
                else_result: else_result.as_ref().map(|e| fb(e)).transpose()?,
            },
            other => other.clone(),
        })
    }
}

/// `ORDER BY`'s own comparator: unlike `value_partial_cmp` (used by
/// `MIN`/`MAX`, which skip NULLs entirely), a sort has to place every row
/// somewhere, so NULL sorts first in ascending order (real MySQL's rule;
/// `Plan::Finish` reverses the whole comparison for `DESC`, which correctly
/// puts NULLs last in that case too, matching MySQL). Two otherwise-
/// incomparable values are treated as equal rather than panicking or being
/// arbitrarily ordered.
pub(crate) fn sort_cmp(a: &Value, b: &Value) -> Ordering {
    match (a.is_null(), b.is_null()) {
        (true, true) => return Ordering::Equal,
        (true, false) => return Ordering::Less,
        (false, true) => return Ordering::Greater,
        (false, false) => {}
    }
    value_partial_cmp(a, b).unwrap_or(Ordering::Equal)
}

/// Ordering used by `MIN`/`MAX`: numeric values compare numerically, text
/// compares lexically, matching `eval_compare`'s own rules. `None` (e.g.
/// comparing a number against text) means the two aren't ordered against
/// each other — the caller treats that as "keep the earlier value".
fn value_partial_cmp(a: &Value, b: &Value) -> Option<Ordering> {
    mysql_cmp(a, b)
}

/// `COUNT`/`SUM`/`AVG`/`MIN`/`MAX` over one group's evaluated values.
/// `COUNT(*)` is handled by the caller before reaching here (it needs the
/// row count, not evaluated values). NULLs are skipped, matching MySQL;
/// an all-NULL (or empty) group's `SUM`/`AVG`/`MIN`/`MAX` is NULL.
fn compute_agg(func: AggFunc, vals: &[Value]) -> Value {
    let non_null: Vec<&Value> = vals.iter().filter(|v| !v.is_null()).collect();
    match func {
        // Computed by `Executor::group_concat`, which needs the rows.
        AggFunc::GroupConcat => Value::Null,
        AggFunc::CountStar => Value::Int(vals.len() as i64),
        AggFunc::Count => Value::Int(non_null.len() as i64),
        AggFunc::Sum | AggFunc::Avg => {
            if non_null.is_empty() {
                return Value::Null;
            }
            // MySQL: an exact (INT/DECIMAL) input sums exactly; any
            // approximate (FLOAT/DOUBLE, or a string coerced to a number)
            // input makes the whole result a DOUBLE. AVG of exact values is
            // a DECIMAL carrying `div_precision_increment` (4) more digits
            // than the inputs (`AVG` of 1,2,2 is 1.6667, not 1.666666...).
            let approximate = non_null
                .iter()
                .any(|v| !matches!(v, Value::Int(_) | Value::Num(_) | Value::Bool(_)));
            if approximate {
                let sum: f64 = non_null.iter().map(|v| value_to_f64(v)).sum();
                return match func {
                    AggFunc::Sum => Value::Float(sum),
                    _ => Value::Float(sum / non_null.len() as f64),
                };
            }
            if matches!(func, AggFunc::Sum) && non_null.iter().all(|v| matches!(v, Value::Int(_))) {
                let mut acc: i64 = 0;
                let mut overflow = false;
                for v in &non_null {
                    if let Value::Int(i) = v {
                        match acc.checked_add(*i) {
                            Some(n) => acc = n,
                            None => overflow = true,
                        }
                    }
                }
                if !overflow {
                    return Value::Int(acc);
                }
            }
            let mut sum = Numeric::zero();
            let mut max_scale = 0u32;
            for v in &non_null {
                if let Some(n) = value_to_numeric(v) {
                    max_scale = max_scale.max(n.scale());
                    sum = sum.add(&n);
                }
            }
            match func {
                AggFunc::Sum => Value::Num(sum),
                _ => {
                    let count = Numeric::from_i64(non_null.len() as i64);
                    match sum.div_scale(&count, max_scale as i64 + 4, false) {
                        Ok(avg) => Value::Num(avg),
                        Err(_) => Value::Null,
                    }
                }
            }
        }
        AggFunc::Min => non_null
            .into_iter()
            .cloned()
            .min_by(|a, b| mysql_cmp(a, b).unwrap_or(Ordering::Equal))
            .unwrap_or(Value::Null),
        AggFunc::Max => non_null
            .into_iter()
            .cloned()
            .max_by(|a, b| mysql_cmp(a, b).unwrap_or(Ordering::Equal))
            .unwrap_or(Value::Null),
    }
}

/// MySQL's lenient string-to-number coercion for a mixed-type comparison
/// or arithmetic operand: parses the longest leading prefix of `s` that
/// looks like a number (optional sign, digits, optional decimal point and
/// more digits) and falls back to 0.0 for anything else, including empty
/// input (e.g. `wp_posts.post_parent = 4` compared against a `Text`-typed
/// "0"/"4" -- a real, common shape for WordPress's own generated SQL).
/// Real MySQL only ever warns about this ("Truncated incorrect DOUBLE
/// value"), it never aborts the query; this engine has no warnings
/// channel to surface that softer signal through, so dropping the
/// warning silently is the closest faithful behavior, not erroring
/// outright.
fn mysql_text_to_f64(s: &str) -> f64 {
    let s = s.trim_start();
    let mut end = 0;
    for (i, c) in s.char_indices() {
        let ok = c.is_ascii_digit()
            || (i == 0 && (c == '+' || c == '-'))
            || (c == '.' && !s[..i].contains('.'));
        if !ok {
            break;
        }
        end = i + c.len_utf8();
    }
    s[..end].parse::<f64>().unwrap_or(0.0)
}

/// Builds the combined column list a joined row's `ColName` lookups
/// resolve against: the left side's real columns followed by the right
/// side's, in the same order `Plan::Join`'s own execution concatenates the
/// two rows (`left_row ++ right_row`) -- so a column's position in this
/// synthetic `Table` always matches its position in the actual row data.
/// Only the `columns` field is ever read back off the result (`rows` and
/// `next_auto_increment` are meaningless for it), so those are left at
/// `Table::new`'s own empty defaults.
///
/// Each merged column is renamed to `"<source table>.<column>"` (using
/// the real table each side's `Table::name` carries), *not* left as its
/// own bare name -- found via testing before a public release:
/// `cust.id`/`orders.id` across a join both resolving by bare name to
/// whichever table's `id` happened to come first, regardless of which one
/// was actually named, silently returned the wrong table's value. Because
/// `resolve_column_index` tries an exact match against the sought name
/// before ever falling back to a bare-suffix match, a genuinely qualified
/// reference (which the binder now always preserves in full, see its own
/// `AstExpr::CompoundIdentifier` comment) matches its real column exactly;
/// only a genuinely unqualified, genuinely ambiguous bare reference
/// (uncommon, and real MySQL itself rejects it as ambiguous rather than
/// picking one) still falls back to "whichever comes first".
fn merge_table_contexts(left: Option<Table>, right: Option<Table>) -> Option<Table> {
    match (left, right) {
        (Some(l), Some(r)) => {
            // A three-or-more-way join merges incrementally (this join's
            // own left/right context may itself already be a previously
            // merged, already-qualified "__join__" table) -- skip
            // re-qualifying a column whose name is already qualified, so
            // a chain of merges never produces a doubly-qualified name
            // like `"__join__.a.x"` that would silently stop matching
            // its own exact-qualified lookup.
            let qualify = |t: Table| -> Vec<Column> {
                t.columns
                    .into_iter()
                    .map(|mut c| {
                        if !c.name.contains('.') {
                            c.name = format!("{}.{}", t.name, c.name);
                        }
                        c
                    })
                    .collect()
            };
            let mut columns = qualify(l);
            columns.extend(qualify(r));
            Some(Table::new("__join__".to_string(), columns))
        }
        _ => None,
    }
}

/// Resolves a (possibly qualified, e.g. `"orders.amount"`) column name
/// against `columns`. Tries an exact match first -- the only way a
/// reference to one specific side of a join (whose merged column list has
/// every name qualified, see `merge_table_contexts`) finds *that* table's
/// column instead of silently aliasing to whichever table's
/// same-named column happens to come first. Falls back to matching by the
/// last dot-separated component on both sides, so a plain unqualified
/// reference (`"amount"`) still finds a qualified column (`"orders.amount"`)
/// and a qualified reference against an ordinary single-table context
/// (whose columns are never qualified) still finds its bare column.
fn resolve_column_index(columns: &[Column], sought: &str) -> Option<usize> {
    if let Some(idx) = columns.iter().position(|c| c.name == sought) {
        return Some(idx);
    }
    // MySQL column names are case-insensitive (`SELECT NAME FROM users`).
    if let Some(idx) = columns.iter().position(|c| c.name.eq_ignore_ascii_case(sought)) {
        return Some(idx);
    }
    let sought_last = sought.rsplit('.').next().unwrap_or(sought);
    columns.iter().position(|c| {
        c.name.rsplit('.').next().unwrap_or(&c.name).eq_ignore_ascii_case(sought_last)
    })
}

/// Coerces a `Value` to a plain string the way `CONCAT`/`UPPER`/`LOWER`/
/// `SUBSTRING`/`LIKE` need it, mirroring the leniency `mysql_text_to_f64`
/// already applies on the numeric side: `NULL` has no text form (the
/// caller decides how to propagate that), and the handful of variants this
/// scalar-function library doesn't have a defined textual form for yet
/// (`Bytes`/`Date`/`Time`/`Ts`/`Json`) return `None` rather than guessing.
pub(crate) fn value_as_text(v: &Value) -> Option<String> {
    if v.is_null() { None } else { Some(render_text(v)) }
}

/// `pattern [ESCAPE esc]` matching for `LIKE`: `%` matches any run of
/// characters (including none), `_` matches exactly one, and `esc`
/// (when given) makes the character right after it literal instead of a
/// wildcard. Case-insensitive, matching MySQL's default `_ci` collations.
/// Same tokenize-then-backtrack algorithm as `postgres::funcs::like`
/// (not shared code -- `mysql` and `postgres` are independent Cargo
/// features, so mysql's own executor can't depend on postgres's module).
pub(crate) fn mysql_like(s: &str, pattern: &str, esc: Option<char>) -> bool {
    enum Tok {
        Lit(char),
        One,
        Any,
    }
    let s: Vec<char> = s.to_lowercase().chars().collect();
    let pattern: Vec<char> = pattern.to_lowercase().chars().collect();
    let esc = esc.map(|c| c.to_ascii_lowercase());

    let mut toks = Vec::with_capacity(pattern.len());
    let mut i = 0;
    while i < pattern.len() {
        let c = pattern[i];
        if Some(c) == esc && i + 1 < pattern.len() {
            toks.push(Tok::Lit(pattern[i + 1]));
            i += 2;
            continue;
        }
        toks.push(match c {
            '%' => Tok::Any,
            '_' => Tok::One,
            c => Tok::Lit(c),
        });
        i += 1;
    }

    let (mut si, mut ti) = (0usize, 0usize);
    let mut star: Option<(usize, usize)> = None;
    while si < s.len() {
        if ti < toks.len() {
            match toks[ti] {
                Tok::Any => {
                    star = Some((ti, si));
                    ti += 1;
                    continue;
                }
                Tok::One => {
                    si += 1;
                    ti += 1;
                    continue;
                }
                Tok::Lit(c) if c == s[si] => {
                    si += 1;
                    ti += 1;
                    continue;
                }
                _ => {}
            }
        }
        match star {
            Some((st, ss)) => {
                ti = st + 1;
                si = ss + 1;
                star = Some((st, ss + 1));
            }
            None => return false,
        }
    }
    while ti < toks.len() && matches!(toks[ti], Tok::Any) {
        ti += 1;
    }
    ti == toks.len()
}

/// The fixed scalar-function library `Expr::Call` dispatches to -- see the
/// comment on that variant. Any argument that can't be coerced to text
/// (`value_as_text` returning `None`, which includes `NULL`) makes the
/// whole call `NULL`, matching real MySQL's own NULL-propagation for
/// these functions.
pub(crate) fn eval_call(name: &str, args: &[Value]) -> Result<Value, MySqlError> {
    match name {
        "CONCAT" => {
            let mut out = String::new();
            for a in args {
                match value_as_text(a) {
                    Some(s) => out.push_str(&s),
                    None => return Ok(Value::Null),
                }
            }
            Ok(Value::Text(out))
        }
        "UPPER" => match args.first().and_then(value_as_text) {
            Some(s) => Ok(Value::Text(s.to_uppercase())),
            None => Ok(Value::Null),
        },
        "LOWER" => match args.first().and_then(value_as_text) {
            Some(s) => Ok(Value::Text(s.to_lowercase())),
            None => Ok(Value::Null),
        },
        "LENGTH" => match args.first().and_then(value_as_text) {
            Some(s) => Ok(Value::Int(s.len() as i64)),
            None => Ok(Value::Null),
        },
        "SUBSTRING" | "SUBSTR" => {
            let Some(s) = args.first().and_then(value_as_text) else {
                return Ok(Value::Null);
            };
            let chars: Vec<char> = s.chars().collect();
            let len = chars.len() as i64;
            // MySQL's `SUBSTRING` is 1-indexed, and a negative start
            // counts from the end of the string (`SUBSTRING('hello', -3)`
            // is `"llo"`).
            let Some(Value::Int(start)) = args.get(1) else { return Ok(Value::Null) };
            let start0 = if *start > 0 {
                start - 1
            } else if *start < 0 {
                (len + start).max(0)
            } else {
                0
            };
            let count = match args.get(2) {
                Some(Value::Int(n)) => (*n).max(0),
                Some(_) => return Ok(Value::Null),
                None => len,
            };
            let begin = start0.clamp(0, len) as usize;
            let end = (start0 + count).clamp(0, len) as usize;
            Ok(Value::Text(chars[begin..end.max(begin)].iter().collect()))
        }
        "COALESCE" => {
            for a in args {
                if !a.is_null() {
                    return Ok(a.clone());
                }
            }
            Ok(Value::Null)
        }
        "IFNULL" => {
            let Some(a) = args.first() else { return Ok(Value::Null) };
            if !a.is_null() {
                Ok(a.clone())
            } else {
                Ok(args.get(1).cloned().unwrap_or(Value::Null))
            }
        }
        // The time of the statement. No session time zone exists, so these
        // are UTC -- the same `now_ts()` a `DEFAULT CURRENT_TIMESTAMP`
        // column is filled with, so the two always agree.
        "NOW" | "CURRENT_TIMESTAMP" | "LOCALTIMESTAMP" | "LOCALTIME" | "SYSDATE" => {
            Ok(Value::Ts(now_ts()))
        }
        "CURDATE" | "CURRENT_DATE" => {
            Ok(Value::Date(now_ts().div_euclid(crate::sql::datetime::USECS_PER_DAY) as i32))
        }
        _ => crate::mysql::funcs::eval(name, args),
    }
}

/// Basic integer/float arithmetic. Only defined for the two numeric
/// `Value` variants this engine's literal parser actually produces
/// (`Int`/`Float`) — mixing in a float promotes the result to float,
/// matching MySQL's own numeric-promotion rule for `+ - * /`.
pub(crate) fn eval_arith(op: ArithOp, l: Value, r: Value) -> Result<Value, MySqlError> {
    // Any arithmetic involving NULL is NULL (`views + 1` on a NULL `views`),
    // never an error -- found via testing before a public release.
    if l.is_null() || r.is_null() {
        return Ok(Value::Null);
    }
    let is_exact = |v: &Value| matches!(v, Value::Int(_) | Value::Num(_) | Value::Bool(_));
    if let (Value::Int(a), Value::Int(b)) = (&l, &r) {
        let (a, b) = (*a, *b);
        let checked = match op {
            ArithOp::Add => a.checked_add(b),
            ArithOp::Sub => a.checked_sub(b),
            ArithOp::Mul => a.checked_mul(b),
            ArithOp::Mod => {
                // `x % 0` is NULL in MySQL, not a division-by-zero error.
                return Ok(if b == 0 { Value::Null } else { Value::Int(a % b) });
            }
            ArithOp::Div => None, // handled exactly below
        };
        if let Some(v) = checked {
            return Ok(Value::Int(v));
        }
        if !matches!(op, ArithOp::Div) {
            return Err(MySqlError::new(
                1690,
                "22003",
                format!("BIGINT value is out of range in '({a} {} {b})'", op_symbol(op)),
            ));
        }
    }
    if is_exact(&l) && is_exact(&r) {
        // Exact DECIMAL arithmetic, the way MySQL does it for INT/DECIMAL
        // operands: `price * 2` on a DECIMAL(10,2) stays exact, and `/`
        // carries `div_precision_increment` (4) more digits than the
        // dividend (`10/4` is 2.5000, `1/3` is 0.3333).
        let (Some(a), Some(b)) = (value_to_numeric(&l), value_to_numeric(&r)) else {
            return Ok(Value::Null);
        };
        return Ok(match op {
            ArithOp::Add => Value::Num(a.add(&b)),
            ArithOp::Sub => Value::Num(a.sub(&b)),
            ArithOp::Mul => Value::Num(a.mul(&b)),
            ArithOp::Div => {
                if b.to_f64() == 0.0 {
                    Value::Null
                } else {
                    match a.div_scale(&b, a.scale() as i64 + 4, false) {
                        Ok(v) => Value::Num(v),
                        Err(_) => Value::Null,
                    }
                }
            }
            ArithOp::Mod => {
                let (x, y) = (a.to_f64(), b.to_f64());
                if y == 0.0 { Value::Null } else { Value::Num(Numeric::from_f64(x % y)) }
            }
        });
    }
    let (a, b) = (value_to_f64(&l), value_to_f64(&r));
    Ok(match op {
        ArithOp::Add => Value::Float(a + b),
        ArithOp::Sub => Value::Float(a - b),
        ArithOp::Mul => Value::Float(a * b),
        ArithOp::Div => {
            if b == 0.0 {
                Value::Null
            } else {
                Value::Float(a / b)
            }
        }
        ArithOp::Mod => {
            if b == 0.0 {
                Value::Null
            } else {
                Value::Float(a % b)
            }
        }
    })
}

/// MySQL's three-valued comparison logic: NULL on either side always
/// yields NULL (never true or false), never an error. Result is 0/1,
/// matching how MySQL represents boolean results.
fn eval_compare(op: CmpOp, l: Value, r: Value) -> Result<Value, MySqlError> {
    if l.is_null() || r.is_null() {
        return Ok(Value::Null);
    }
    let Some(ordering) = mysql_cmp(&l, &r) else {
        return Ok(Value::Null);
    };
    let result = match op {
        CmpOp::Eq => ordering == Ordering::Equal,
        CmpOp::Ne => ordering != Ordering::Equal,
        CmpOp::Lt => ordering == Ordering::Less,
        CmpOp::Le => ordering != Ordering::Greater,
        CmpOp::Gt => ordering == Ordering::Greater,
        CmpOp::Ge => ordering != Ordering::Less,
    };
    Ok(Value::Int(result as i64))
}

/// `l [NOT] IN (items...)`, matching real MySQL's three-valued semantics:
/// true if `l` equals any non-NULL item (via `eval_compare`'s own
/// equality, so the same type-coercion/ordering rules apply), else NULL
/// if `l` or any item is NULL, else false. `negated` flips true/false but
/// leaves NULL as NULL, the same way `NOT NULL` (the boolean operator, not
/// the column constraint) does.
fn eval_in_list(l: Value, items: &[Value], negated: bool) -> Result<Value, MySqlError> {
    let mut any_null = l.is_null();
    let mut found = false;
    for item in items {
        if item.is_null() {
            any_null = true;
            continue;
        }
        if eval_compare(CmpOp::Eq, l.clone(), item.clone())? == Value::Int(1) {
            found = true;
        }
    }
    if any_null && !found {
        return Ok(Value::Null); // NOT NULL is still NULL
    }
    Ok(Value::Int((found != negated) as i64))
}

fn op_symbol(op: ArithOp) -> &'static str {
    match op {
        ArithOp::Add => "+",
        ArithOp::Sub => "-",
        ArithOp::Mul => "*",
        ArithOp::Div => "/",
        ArithOp::Mod => "%",
    }
}

/// The current time as a `DATETIME` value (microseconds since 2000-01-01,
/// the encoding `Value::Ts` shares with the Postgres engine), truncated to
/// whole seconds the way a plain `DATETIME`/`NOW()` is.
pub(crate) fn now_ts() -> i64 {
    let us = crate::sql::datetime::now_micros();
    us - us.rem_euclid(crate::sql::datetime::USECS_PER_SEC)
}

fn datetime_ctx<R>(f: impl FnOnce(&crate::sql::datetime::Ctx) -> R) -> R {
    let zone = crate::sql::tz::Zone::utc();
    let ctx = crate::sql::datetime::Ctx { now: now_ts(), zone: &zone };
    f(&ctx)
}

/// A `DATE` from text (`'2024-03-05'`, or the date part of a datetime).
/// `None` for anything unparseable, including MySQL's own zero date
/// `'0000-00-00'`, which callers keep as text rather than reject.
pub(crate) fn parse_mysql_date(s: &str) -> Option<i32> {
    datetime_ctx(|ctx| crate::sql::datetime::parse_date(s.trim(), ctx).ok())
}

/// A `DATETIME` from text (`'2024-03-05 14:07:09[.ffffff]'`, or a bare
/// date at midnight). `None` for unparseable/zero values.
pub(crate) fn parse_mysql_datetime(s: &str) -> Option<i64> {
    datetime_ctx(|ctx| crate::sql::datetime::parse_timestamp(s.trim(), ctx).ok())
}

pub(crate) fn value_to_f64(v: &Value) -> f64 {
    match v {
        Value::Int(i) => *i as f64,
        Value::Float(f) => *f,
        Value::Num(n) => n.to_f64(),
        Value::Bool(b) => *b as i64 as f64,
        Value::Text(s) => mysql_text_to_f64(s),
        _ => 0.0,
    }
}

pub(crate) fn value_to_numeric(v: &Value) -> Option<Numeric> {
    match v {
        Value::Int(i) => Some(Numeric::from_i64(*i)),
        Value::Num(n) => Some(n.clone()),
        Value::Bool(b) => Some(Numeric::from_i64(*b as i64)),
        Value::Float(f) => Some(Numeric::from_f64(*f)),
        Value::Text(s) => {
            Numeric::parse(s.trim()).ok().or_else(|| Some(Numeric::from_f64(mysql_text_to_f64(s))))
        }
        _ => None,
    }
}

/// MySQL's comparison rules, shared by `=`/`<`/..., `IN`, `MIN`/`MAX` and
/// `ORDER BY` so every one of them agrees:
/// - text vs text: case-insensitive, like MySQL's default `_ci` collations
///   (`WHERE email = 'Alice@X.com'` matches `alice@x.com`);
/// - numbers: exact when both sides are exact (INT/DECIMAL), as doubles
///   otherwise; text compared with a number is coerced to a number;
/// - DATE/DATETIME: chronologically, including against a date string
///   (`created_at >= '2024-01-01'`).
///
/// `None` only for a NaN.
pub(crate) fn mysql_cmp(a: &Value, b: &Value) -> Option<Ordering> {
    use Value::*;
    let is_numeric = |v: &Value| matches!(v, Int(_) | Float(_) | Num(_) | Bool(_));
    let is_temporal = |v: &Value| matches!(v, Date(_) | Ts(_));
    match (a, b) {
        (Text(x), Text(y)) => Some(x.to_lowercase().cmp(&y.to_lowercase())),
        (Date(x), Date(y)) => Some(x.cmp(y)),
        (Ts(x), Ts(y)) => Some(x.cmp(y)),
        (Date(x), Ts(y)) => Some((*x as i64 * crate::sql::datetime::USECS_PER_DAY).cmp(y)),
        (Ts(x), Date(y)) => Some(x.cmp(&(*y as i64 * crate::sql::datetime::USECS_PER_DAY))),
        (Date(_) | Ts(_), Text(s)) => match parse_mysql_datetime(s) {
            Some(t) => mysql_cmp(a, &Ts(t)),
            None => Some(render_text(a).cmp(s)),
        },
        (Text(_), Date(_) | Ts(_)) => mysql_cmp(b, a).map(Ordering::reverse),
        _ if is_temporal(a) || is_temporal(b) => Some(render_text(a).cmp(&render_text(b))),
        (Int(x), Int(y)) => Some(x.cmp(y)),
        _ if (is_numeric(a) || matches!(a, Text(_))) && (is_numeric(b) || matches!(b, Text(_))) => {
            let exact = |v: &Value| matches!(v, Int(_) | Num(_) | Bool(_));
            if exact(a) && exact(b) {
                let (x, y) = (value_to_numeric(a)?, value_to_numeric(b)?);
                Some(crate::sql::numeric::cmp_num(&x, &y))
            } else {
                value_to_f64(a).partial_cmp(&value_to_f64(b))
            }
        }
        _ => Some(render_text(a).cmp(&render_text(b))),
    }
}

/// A value's MySQL text form -- exactly what the text protocol sends for
/// it, and what a value is compared/concatenated as when it has to be
/// treated as a string.
pub(crate) fn render_text(v: &Value) -> String {
    match v {
        Value::Null => String::new(),
        Value::Text(s) => s.clone(),
        Value::Int(i) => i.to_string(),
        Value::Bool(b) => (*b as i64).to_string(),
        Value::Float(f) => format_double(*f),
        Value::Num(n) => n.to_string(),
        Value::Date(d) => crate::sql::datetime::format_date(*d),
        // MySQL prints fractional seconds as all six digits (`.000600`),
        // never trimmed the way Postgres does (`.0006`).
        Value::Ts(t) => mysql_fraction(crate::sql::datetime::format_timestamp(*t), *t),
        Value::Time(t) => mysql_fraction(crate::sql::datetime::format_time(*t), *t),
        Value::Bytes(b) => String::from_utf8_lossy(b).into_owned(),
        Value::Json(j) => j.to_jsonb_string(),
    }
}

/// MySQL prints a DOUBLE in its shortest round-trip form, with no
/// trailing `.0` on an integral value (`2`, not `2.0`).
pub(crate) fn format_double(f: f64) -> String {
    if f.is_finite() && f == f.trunc() && f.abs() < 1e15 {
        format!("{}", f as i64)
    } else {
        format!("{f}")
    }
}

/// Converts a value to the type of the column it's being written to, the
/// way real MySQL does on INSERT/UPDATE: a DECIMAL column stores an exact
/// value rounded to its scale (`12.5` into DECIMAL(10,2) reads back as
/// `12.50`), FLOAT/DOUBLE store a double, integer columns an integer, DATE
/// and DATETIME a real date/time. Found via testing before a public
/// release: values used to be stored in whatever shape the literal arrived
/// in, so a DECIMAL column filled from `12.50` held *text*, and SUM/AVG/
/// MAX/ORDER BY/`>` on it were all silently wrong.
/// `[min, max]` for an integer column type.
fn int_range(ty: &ColumnType, unsigned: bool) -> Option<(i128, i128)> {
    let bits = match ty {
        ColumnType::TinyInt | ColumnType::Boolean => 8,
        ColumnType::SmallInt => 16,
        ColumnType::MediumInt => 24,
        ColumnType::Int => 32,
        ColumnType::BigInt => 64,
        _ => return None,
    };
    Some(if unsigned {
        (0, (1i128 << bits) - 1)
    } else {
        (-(1i128 << (bits - 1)), (1i128 << (bits - 1)) - 1)
    })
}

/// Stores `v` as column `col`'s type, the way MySQL converts on write. In
/// strict mode (MySQL 8's default) a value that doesn't fit is an error;
/// otherwise it's adjusted the way MySQL adjusts it -- clamped,
/// truncated, or zeroed. Found via a differential test against real MySQL:
/// out-of-range integers and invalid dates used to be stored as given.
pub(crate) fn coerce_to_column(
    v: Value,
    col: &Column,
    mode: &crate::mysql::sqlmode::SqlMode,
) -> Result<Value, MySqlError> {
    use Value::*;
    if v.is_null() {
        return Ok(Null);
    }
    let name = col.name.as_str();
    let strict = mode.strict();
    let err = |code: u16, state: &'static str, msg: String| Err(MySqlError::new(code, state, msg));
    let incorrect = |what: &str, v: &Value| {
        err(
            1366,
            "HY000",
            format!("Incorrect {what} value: '{}' for column '{name}' at row 1", render_text(v)),
        )
    };
    let out_of_range =
        || err(1264, "22003", format!("Out of range value for column '{name}' at row 1"));
    Ok(match &col.ty {
        ty @ (ColumnType::Int
        | ColumnType::BigInt
        | ColumnType::Boolean
        | ColumnType::TinyInt
        | ColumnType::SmallInt
        | ColumnType::MediumInt) => {
            let n: i128 = match &v {
                Int(i) => *i as i128,
                Bool(b) => *b as i128,
                Float(f) => f.round() as i128,
                Num(n) => n.to_f64().round() as i128,
                Text(s) => {
                    let t = s.trim();
                    match t.parse::<i128>() {
                        Ok(i) => i,
                        Err(_) => match t.parse::<f64>() {
                            Ok(f) => f.round() as i128,
                            Err(_) if strict => return incorrect("integer", &v),
                            Err(_) => crate::mysql::funcs::leading_f64(t).round() as i128,
                        },
                    }
                }
                _ if strict => return incorrect("integer", &v),
                _ => 0,
            };
            let (lo, hi) = int_range(ty, col.unsigned).unwrap();
            if n < lo || n > hi {
                if strict {
                    return out_of_range();
                }
                Int(n.clamp(lo, hi).min(i64::MAX as i128) as i64)
            } else {
                Int(n as i64)
            }
        }
        ColumnType::Float | ColumnType::Double => match &v {
            Float(_) => v,
            Int(_) | Num(_) | Bool(_) => Float(value_to_f64(&v)),
            Text(s) => match s.trim().parse::<f64>() {
                Ok(f) => Float(f),
                Err(_) if strict => return incorrect("double", &v),
                Err(_) => Float(crate::mysql::funcs::leading_f64(s)),
            },
            _ if strict => return incorrect("double", &v),
            _ => Float(0.0),
        },
        ColumnType::Decimal(precision, scale) => {
            let n = match &v {
                Text(s) => match Numeric::parse(s.trim()) {
                    Ok(n) => n,
                    Err(_) if strict => return incorrect("decimal", &v),
                    Err(_) => Numeric::from_f64(crate::mysql::funcs::leading_f64(s)),
                },
                Int(_) | Num(_) | Float(_) | Bool(_) => {
                    value_to_numeric(&v).unwrap_or_else(Numeric::zero)
                }
                _ if strict => return incorrect("decimal", &v),
                _ => Numeric::zero(),
            };
            let n = n.round(*scale as i64);
            // DECIMAL(p, s) holds at most p - s digits before the point.
            let int_digits = (*precision as i64 - *scale as i64).max(0);
            let limit = Numeric::parse(&format!("1{}", "0".repeat(int_digits as usize)))
                .unwrap_or_else(|_| Numeric::zero());
            if crate::sql::numeric::cmp_num(&n.abs(), &limit) != Ordering::Less {
                if strict {
                    return out_of_range();
                }
                let max = format!(
                    "{}{}{}",
                    "9".repeat(int_digits as usize),
                    if *scale > 0 { "." } else { "" },
                    "9".repeat(*scale as usize)
                );
                let max = Numeric::parse(&max).unwrap_or_else(|_| Numeric::zero());
                Num(if n.is_negative() { max.neg() } else { max })
            } else {
                Num(n)
            }
        }
        ColumnType::Date | ColumnType::Datetime => {
            let is_date = col.ty == ColumnType::Date;
            let parsed = match &v {
                Date(d) => Some(if is_date {
                    Date(*d)
                } else {
                    Ts(*d as i64 * crate::sql::datetime::USECS_PER_DAY)
                }),
                Ts(t) => Some(if is_date {
                    Date(t.div_euclid(crate::sql::datetime::USECS_PER_DAY) as i32)
                } else {
                    Ts(*t)
                }),
                other => {
                    let s = render_text(other);
                    if is_date {
                        parse_mysql_date(&s).map(Date)
                    } else {
                        parse_mysql_datetime(&s).map(Ts)
                    }
                }
            };
            let zero = if is_date { "0000-00-00" } else { "0000-00-00 00:00:00" };
            match parsed {
                Some(x) => x,
                None => {
                    let s = render_text(&v);
                    let is_zero = s
                        .trim()
                        .trim_start_matches('0')
                        .trim_start_matches(['-', ' ', ':', '0'])
                        .is_empty()
                        && s.trim().starts_with("0000-00-00");
                    // A zero date is fine unless strict mode forbids it;
                    // anything else unparseable is an error in strict mode
                    // and becomes the zero date otherwise.
                    if strict && (!is_zero || mode.no_zero_date()) {
                        let what = if is_date { "date" } else { "datetime" };
                        return err(
                            1292,
                            "22007",
                            format!("Incorrect {what} value: '{s}' for column '{name}' at row 1"),
                        );
                    }
                    Text(zero.to_string())
                }
            }
        }
        ColumnType::Varchar(n) => {
            let t = match v {
                Text(t) => t,
                other => render_text(&other),
            };
            if t.chars().count() > *n {
                if strict {
                    return err(
                        1406,
                        "22001",
                        format!("Data too long for column '{name}' at row 1"),
                    );
                }
                Text(t.chars().take(*n).collect())
            } else {
                Text(t)
            }
        }
        ColumnType::Text => match v {
            Text(_) => v,
            other => Text(render_text(&other)),
        },
        ColumnType::Blob => match v {
            Bytes(_) | Text(_) => v,
            other => Text(render_text(&other)),
        },
        ColumnType::Enum(members) => {
            let t = render_text(&v);
            // Enum values match case-insensitively and are stored as the
            // member's own spelling; a number picks the member by position.
            let found =
                members.iter().find(|m| m.eq_ignore_ascii_case(t.trim_end())).or_else(|| match v {
                    Int(i) if i >= 1 => members.get(i as usize - 1),
                    _ => None,
                });
            match found {
                Some(m) => Text(m.clone()),
                None if strict => {
                    return err(
                        1265,
                        "01000",
                        format!("Data truncated for column '{name}' at row 1"),
                    );
                }
                None => Text(String::new()),
            }
        }
        ColumnType::Json => match v {
            Json(_) => v,
            Text(ref s) => match crate::sql::json::parse_jsonb(s) {
                Ok(j) => Json(Box::new(j)),
                Err(_) => {
                    return err(
                        3140,
                        "22032",
                        format!(
                            "Invalid JSON text: \"Invalid value.\" at position 0 in value for column '{name}'."
                        ),
                    );
                }
            },
            Int(i) => Json(Box::new(crate::sql::json::parse_jsonb(&i.to_string()).unwrap())),
            other => Text(render_text(&other)),
        },
    })
}

/// Row equality for `DISTINCT`: column by column with MySQL's comparison
/// rules, except that two NULLs count as the same value (SQL's DISTINCT
/// treats NULLs as equal to each other, unlike `=`).
/// A table context for a derived table or CTE: its alias and its output
/// column names.
fn derived_table(alias: &str, names: &[String]) -> Table {
    let columns = names
        .iter()
        .map(|n| Column {
            name: n.rsplit('.').next().unwrap_or(n).to_string(),
            ty: ColumnType::Text,
            not_null: false,
            default: None,
            auto_increment: false,
            primary_key: false,
            default_now: false,
            on_update_now: false,
            unsigned: false,
        })
        .collect();
    Table::new(alias.to_string(), columns)
}

/// `UNION`/`INTERSECT`/`EXCEPT` over two row sets: duplicates removed
/// unless `all`, compared the way `DISTINCT` compares.
fn set_op(
    op: SetOpKind,
    all: bool,
    left: Vec<Vec<Value>>,
    right: Vec<Vec<Value>>,
) -> Vec<Vec<Value>> {
    let dedupe = |rows: Vec<Vec<Value>>| {
        let mut kept: Vec<Vec<Value>> = Vec::with_capacity(rows.len());
        for r in rows {
            if !kept.iter().any(|k| rows_distinct_equal(k, &r)) {
                kept.push(r);
            }
        }
        kept
    };
    match op {
        SetOpKind::Union => {
            let mut rows = left;
            rows.extend(right);
            if all { rows } else { dedupe(rows) }
        }
        SetOpKind::Intersect | SetOpKind::Except => {
            let keep_matches = op == SetOpKind::Intersect;
            let mut pool = right;
            let mut out = Vec::new();
            for r in left {
                let hit = pool.iter().position(|p| rows_distinct_equal(p, &r));
                if all && let Some(i) = hit {
                    // Multiset semantics: each right row matches once.
                    pool.swap_remove(i);
                }
                if hit.is_some() == keep_matches {
                    out.push(r);
                }
            }
            if all { out } else { dedupe(out) }
        }
    }
}

fn rows_distinct_equal(a: &[Value], b: &[Value]) -> bool {
    a.len() == b.len()
        && a.iter().zip(b).all(|(x, y)| match (x.is_null(), y.is_null()) {
            (true, true) => true,
            (false, false) => mysql_cmp(x, y) == Some(Ordering::Equal),
            _ => false,
        })
}

/// The first existing row (other than `skip`) that `row` collides with on
/// some key, as `(row index, index into keys)`. A key with a NULL in any of
/// its columns never collides -- MySQL's UNIQUE allows any number of NULLs.
/// Values compare the way the column's collation does (`mysql_cmp`), so
/// 'Bob' and 'bob' are the same key, as in real MySQL.
fn find_key_conflict(
    t: &Table,
    keys: &[(String, Vec<usize>)],
    row: &[Value],
    skip: Option<usize>,
) -> Option<(usize, usize)> {
    for (k, (_, cols)) in keys.iter().enumerate() {
        if cols.iter().any(|&c| row[c].is_null()) {
            continue;
        }
        for (i, other) in t.rows.iter().enumerate() {
            if Some(i) == skip {
                continue;
            }
            if cols.iter().all(|&c| mysql_cmp(&row[c], &other[c]) == Some(Ordering::Equal)) {
                return Some((i, k));
            }
        }
    }
    None
}

/// MySQL 8's `ER_DUP_ENTRY`: `Duplicate entry 'a-b' for key 't.k'`.
fn duplicate_key_error(t: &Table, key: &(String, Vec<usize>), row: &[Value]) -> MySqlError {
    let entry: Vec<String> = key.1.iter().map(|&c| render_text(&row[c])).collect();
    MySqlError::new(
        1062,
        "23000",
        format!("Duplicate entry '{}' for key '{}.{}'", entry.join("-"), t.name, key.0),
    )
}

/// MySQL's `ER_BAD_NULL_ERROR` (strict mode, the 8.0 default).
fn column_cannot_be_null(col: &str) -> MySqlError {
    MySqlError::new(1048, "23000", format!("Column '{col}' cannot be null"))
}

/// A column type as MySQL itself spells it (`DESCRIBE`, `SHOW CREATE TABLE`,
/// `information_schema`), not the Rust enum's debug name.
pub(crate) fn mysql_type_name(ty: &ColumnType) -> String {
    match ty {
        ColumnType::Int => "int".into(),
        ColumnType::BigInt => "bigint".into(),
        ColumnType::TinyInt => "tinyint".into(),
        ColumnType::SmallInt => "smallint".into(),
        ColumnType::MediumInt => "mediumint".into(),
        ColumnType::Varchar(n) => format!("varchar({n})"),
        ColumnType::Text => "text".into(),
        ColumnType::Float => "float".into(),
        ColumnType::Double => "double".into(),
        ColumnType::Decimal(p, s) => format!("decimal({p},{s})"),
        ColumnType::Date => "date".into(),
        ColumnType::Datetime => "datetime".into(),
        ColumnType::Boolean => "tinyint(1)".into(),
        ColumnType::Enum(m) => format!(
            "enum({})",
            m.iter().map(|v| format!("'{}'", v.replace('\'', "''"))).collect::<Vec<_>>().join(",")
        ),
        ColumnType::Json => "json".into(),
        ColumnType::Blob => "blob".into(),
    }
}

fn column_default_text(col: &Column) -> Option<String> {
    if col.default_now {
        return Some("CURRENT_TIMESTAMP".into());
    }
    match &col.default {
        None | Some(Value::Null) => None,
        Some(v) => Some(render_text(v)),
    }
}

/// With no rows to evaluate against, an unknown column would go unnoticed;
/// MySQL rejects it (1054) whether or not the table has rows.
fn check_columns<'a>(
    exprs: impl Iterator<Item = &'a Expr>,
    table: Option<&Table>,
    outer: &[(Table, Vec<Value>)],
) -> Result<(), MySqlError> {
    let Some(t) = table else { return Ok(()) };
    let mut res = Ok(());
    for e in exprs {
        crate::mysql::plan::for_each_colname(e, &mut |name| {
            if res.is_ok() {
                let in_outer =
                    || outer.iter().any(|(o, _)| matches!(resolve_column(o, name), Ok(Some(_))));
                res = match resolve_column(t, name) {
                    Ok(Some(_)) => Ok(()),
                    Ok(None) if in_outer() => Ok(()),
                    Ok(None) => Err(MySqlError::new(
                        1054,
                        "42S22",
                        format!("Unknown column '{name}' in 'field list'"),
                    )),
                    Err(e) => Err(e),
                };
            }
        });
    }
    res
}

/// Resolves a column reference in an expression the way MySQL does:
/// `t.col` must name a column of table (or alias) `t`; a bare `col` must be
/// unique across the joined tables (error 1052 if it's in more than one).
/// `None` means no such column (the caller reports 1054).
fn resolve_column(t: &Table, sought: &str) -> Result<Option<usize>, MySqlError> {
    let cols = &t.columns;
    if let Some(i) =
        cols.iter().position(|c| c.name == sought || c.name.eq_ignore_ascii_case(sought))
    {
        return Ok(Some(i));
    }
    let is_join = cols.iter().any(|c| c.name.contains('.'));
    match sought.rsplit_once('.') {
        // Qualified: in a single-table context the qualifier must be that
        // table (or its alias); in a join, the exact-name match above was
        // the only way to match.
        Some((q, col)) => {
            let q = q.rsplit('.').next().unwrap_or(q);
            if is_join || !(q.eq_ignore_ascii_case(&t.name)) {
                return Ok(None);
            }
            Ok(cols.iter().position(|c| c.name.eq_ignore_ascii_case(col)))
        }
        None => {
            let matches: Vec<usize> = cols
                .iter()
                .enumerate()
                .filter(|(_, c)| {
                    c.name.rsplit('.').next().unwrap_or(&c.name).eq_ignore_ascii_case(sought)
                })
                .map(|(i, _)| i)
                .collect();
            match matches.as_slice() {
                [] => Ok(None),
                [i] => Ok(Some(*i)),
                _ => Err(MySqlError::new(
                    1052,
                    "23000",
                    format!("Column '{sought}' in field list is ambiguous"),
                )),
            }
        }
    }
}

/// A UNIQUE (or PRIMARY) key over existing rows: error 1062 if they
/// already collide, else added.
fn add_unique_key(t: &mut Table, key: UniqueKey) -> Result<(), MySqlError> {
    let mut probe = t.clone();
    probe.unique_keys = vec![key.clone()];
    for c in probe.columns.iter_mut() {
        c.primary_key = false;
    }
    let keys = probe.keys();
    let rows = std::mem::take(&mut probe.rows);
    for row in rows {
        if let Some((_, k)) = find_key_conflict(&probe, &keys, &row, None) {
            return Err(duplicate_key_error(&probe, &keys[k], &row));
        }
        probe.rows.push(row);
    }
    t.unique_keys.retain(|k| !k.name.eq_ignore_ascii_case(&key.name));
    t.unique_keys.push(key);
    Ok(())
}

/// The value an existing row gets for a column `ALTER TABLE ... ADD`s:
/// its default, else NULL, else (NOT NULL) the type's implicit default.
fn added_column_value(col: &Column) -> Value {
    if col.default_now {
        return Value::Ts(now_ts());
    }
    if let Some(d) = &col.default {
        return d.clone();
    }
    if !col.not_null {
        return Value::Null;
    }
    match &col.ty {
        ColumnType::Int
        | ColumnType::BigInt
        | ColumnType::Boolean
        | ColumnType::TinyInt
        | ColumnType::SmallInt
        | ColumnType::MediumInt => Value::Int(0),
        ColumnType::Decimal(..) => Value::Num(Numeric::zero()),
        ColumnType::Float | ColumnType::Double => Value::Float(0.0),
        ColumnType::Enum(m) => Value::Text(m.first().cloned().unwrap_or_default()),
        ColumnType::Date => Value::Text("0000-00-00".into()),
        ColumnType::Datetime => Value::Text("0000-00-00 00:00:00".into()),
        _ => Value::Text(String::new()),
    }
}

fn column_index_or_err(t: &Table, name: &str, what: &str) -> Result<usize, MySqlError> {
    t.columns.iter().position(|c| c.name.eq_ignore_ascii_case(name)).ok_or_else(|| {
        MySqlError::new(1054, "42S22", format!("Unknown column '{name}' in '{what}'"))
    })
}

fn place_column(
    t: &mut Table,
    from: usize,
    pos: Option<crate::mysql::plan::ColumnPos>,
) -> Result<(), MySqlError> {
    use crate::mysql::plan::ColumnPos;
    let to = match pos {
        None => return Ok(()),
        Some(ColumnPos::First) => 0,
        Some(ColumnPos::After(c)) => {
            let i = column_index_or_err(t, &c, "field list")?;
            if i < from { i + 1 } else { i }
        }
    };
    let col = t.columns.remove(from);
    t.columns.insert(to, col);
    for row in t.rows.iter_mut() {
        let v = row.remove(from);
        row.insert(to, v);
    }
    Ok(())
}

/// Applies one `ALTER TABLE` operation to `t` (a copy: a failing operation
/// leaves the real table untouched).
fn alter_table(
    t: &mut Table,
    op: crate::mysql::plan::AlterOp,
    rename_to: &mut Option<String>,
    mode: &crate::mysql::sqlmode::SqlMode,
) -> Result<(), MySqlError> {
    use crate::mysql::plan::AlterOp;
    match op {
        AlterOp::AddColumn { col, unique, pos, if_not_exists } => {
            if t.columns.iter().any(|c| c.name.eq_ignore_ascii_case(&col.name)) {
                if if_not_exists {
                    return Ok(());
                }
                return Err(MySqlError::new(
                    1060,
                    "42S21",
                    format!("Duplicate column name '{}'", col.name),
                ));
            }
            let mut next_id = t.next_auto_increment;
            for row in t.rows.iter_mut() {
                let v = if col.auto_increment {
                    next_id += 1;
                    Value::Int(next_id - 1)
                } else {
                    added_column_value(&col)
                };
                row.push(v);
            }
            if col.auto_increment {
                t.next_auto_increment = next_id;
            }
            t.columns.push(col);
            let at = t.columns.len() - 1;
            place_column(t, at, pos)?;
            for k in unique {
                add_unique_key(t, k)?;
            }
        }
        AlterOp::DropColumn { name, if_exists } => {
            let Some(i) = t.columns.iter().position(|c| c.name.eq_ignore_ascii_case(&name)) else {
                if if_exists {
                    return Ok(());
                }
                return Err(MySqlError::new(
                    1091,
                    "42000",
                    format!("Can't DROP '{name}'; check that column/key exists"),
                ));
            };
            t.columns.remove(i);
            for row in t.rows.iter_mut() {
                row.remove(i);
            }
            t.unique_keys.retain(|k| !k.columns.iter().any(|c| c.eq_ignore_ascii_case(&name)));
        }
        AlterOp::ReplaceColumn { old, mut col, unique, pos } => {
            let i = column_index_or_err(t, &old, "field list")?;
            col.primary_key |= t.columns[i].primary_key;
            for row in t.rows.iter_mut() {
                let v = std::mem::replace(&mut row[i], Value::Null);
                if v.is_null() && col.not_null {
                    return Err(MySqlError::new(1138, "22004", "Invalid use of NULL value"));
                }
                row[i] = coerce_to_column(v, &col, mode)?;
            }
            if !old.eq_ignore_ascii_case(&col.name) {
                for k in t.unique_keys.iter_mut() {
                    for c in k.columns.iter_mut() {
                        if c.eq_ignore_ascii_case(&old) {
                            *c = col.name.clone();
                        }
                    }
                }
            }
            t.columns[i] = col;
            place_column(t, i, pos)?;
            for k in unique {
                add_unique_key(t, k)?;
            }
        }
        AlterOp::RenameColumn { old, new } => {
            let i = column_index_or_err(t, &old, "field list")?;
            for k in t.unique_keys.iter_mut() {
                for c in k.columns.iter_mut() {
                    if c.eq_ignore_ascii_case(&old) {
                        *c = new.clone();
                    }
                }
            }
            t.columns[i].name = new;
        }
        AlterOp::RenameTable(new) => *rename_to = Some(new),
        AlterOp::AddUnique(key) => {
            for c in &key.columns {
                column_index_or_err(t, c, "key")?;
            }
            add_unique_key(t, key)?;
        }
        AlterOp::AddPrimaryKey(cols) => {
            if t.columns.iter().any(|c| c.primary_key) {
                return Err(MySqlError::new(1068, "42000", "Multiple primary key defined"));
            }
            let mut idx = Vec::new();
            for c in &cols {
                idx.push(column_index_or_err(t, c, "key")?);
            }
            add_unique_key(t, UniqueKey { name: "PRIMARY".into(), columns: cols })?;
            t.unique_keys.retain(|k| k.name != "PRIMARY");
            for i in idx {
                t.columns[i].primary_key = true;
                t.columns[i].not_null = true;
            }
        }
        AlterOp::DropKey(name) if name.eq_ignore_ascii_case("PRIMARY") => {
            t.columns.iter_mut().for_each(|c| c.primary_key = false);
        }
        // A plain (non-unique) index isn't tracked, so dropping one that
        // isn't a UNIQUE key is a no-op rather than an error.
        AlterOp::DropKey(name) => t.unique_keys.retain(|k| !k.name.eq_ignore_ascii_case(&name)),
        AlterOp::DropPrimaryKey => t.columns.iter_mut().for_each(|c| c.primary_key = false),
        AlterOp::SetDefault { col, default, now } => {
            let i = column_index_or_err(t, &col, "field list")?;
            t.columns[i].default = default;
            t.columns[i].default_now = now;
        }
        AlterOp::AutoIncrement(n) => t.next_auto_increment = t.next_auto_increment.max(n),
        AlterOp::Noop => {}
    }
    Ok(())
}

/// Pads a trimmed fractional-seconds part back out to six digits.
fn mysql_fraction(text: String, micros: i64) -> String {
    if micros.rem_euclid(1_000_000) == 0 {
        return text;
    }
    match text.rsplit_once('.') {
        Some((head, frac)) if frac.len() < 6 && frac.chars().all(|c| c.is_ascii_digit()) => {
            format!("{head}.{frac:0<6}")
        }
        _ => text,
    }
}
